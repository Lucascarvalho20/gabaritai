  'direito-penal',
  'Princípios do Direito Penal',
  'Princípios do Direito Penal: Legalidade, Anterioridade, Intervenção Mínima e demais',

E'# Princípios do Direito Penal\n\n'
'## 1. Visão geral\n\n'
'Os princípios do Direito Penal são os **vetores axiológicos** que orientam toda a construção e aplicação do sistema penal — desde a criação dos tipos pelo legislador até a interpretação judicial. Servem como **garantia do cidadão contra o poder punitivo do Estado** (jus puniendi).\n\n'
'Têm fundamento constitucional (CF arts. 1º, 5º), penal (CP arts. 1º a 12) e em tratados internacionais (Convenção Americana de Direitos Humanos — Pacto de São José da Costa Rica).\n\n'
'## 2. Princípio da Legalidade (CF 5º XXXIX, CP art. 1º)\n\n'
'### 2.1. Conceito\n\n'
'**"Nullum crimen, nulla poena sine lege"** — não há crime nem pena sem lei anterior que os defina.\n\n'
'**CF art. 5º, XXXIX:** *"não há crime sem lei anterior que o defina, nem pena sem prévia cominação legal"*\n\n'
'**CP art. 1º:** mesma redação.\n\n'
'### 2.2. Subprincípios\n\n'
'A legalidade desdobra-se em:\n\n'
'**a) Reserva legal (nullum crimen sine lege):** apenas a **lei em sentido estrito** (lei ordinária ou complementar) pode criar tipos penais. Não cabem decretos, regulamentos, MP (CF 62, § 1º, b).\n\n'
'**b) Anterioridade (nullum crimen sine lege praevia):** a lei penal deve ser **anterior** ao fato. Vedada retroatividade para prejudicar (salvo a benéfica).\n\n'
'**c) Taxatividade (lex certa):** a lei penal deve descrever com **clareza, precisão e determinação** o fato típico. Vedam-se tipos vagos, abertos ou genéricos demais.\n\n'
'**d) Vedação à analogia in malam partem:** não cabe analogia para **prejudicar** o réu. Cabe analogia **in bonam partem** (favorável).\n\n'
'## 3. Princípio da Anterioridade\n\n'
'### 3.1. Conceito\n\n'
'A lei penal **só atinge fatos ocorridos após sua vigência** (tempus regit actum). É consequência direta da legalidade.\n\n'
'### 3.2. Exceção: lei penal mais benéfica\n\n'
'**CP art. 2º + CF 5º, XL:** *"a lei penal não retroagirá, salvo para beneficiar o réu"*.\n\n'
'Detalhamento no material 2.\n\n'
'## 4. Princípio da Intervenção Mínima (Ultima Ratio)\n\n'
'### 4.1. Conceito\n\n'
'O Direito Penal deve ser a **última instância** de controle social — apenas para proteger os bens jurídicos mais importantes contra as agressões mais graves. Outros ramos (civil, administrativo) devem ser preferidos.\n\n'
'### 4.2. Vertentes\n\n'
'**a) Fragmentariedade:** o Direito Penal protege apenas **fragmentos** dos bens jurídicos — não tudo o que se protege civilmente é também crime.\n\n'
'**b) Subsidiariedade:** o Direito Penal é **subsidiário** — só atua quando outros ramos forem insuficientes.\n\n'
'### 4.3. Aplicação\n\n'
'Justifica a **descriminalização** de certos tipos (adultério, vadiagem em parte) e a **bagatela** (insignificância).\n\n'
'## 5. Princípio da Insignificância (Bagatela)\n\n'
'### 5.1. Conceito\n\n'
'**Construção do STF/STJ** (não escrito): condutas que afetam **minimamente** o bem jurídico não devem ser punidas — ainda que formalmente típicas.\n\n'
'### 5.2. Requisitos (STF HC 84.412, mantidos pela jurisprudência)\n\n'
'1. **Mínima ofensividade da conduta**\n'
'2. **Ausência de periculosidade social**\n'
'3. **Reduzido grau de reprovabilidade**\n'
'4. **Inexpressividade da lesão jurídica**\n\n'
'### 5.3. Aplicação\n\n'
'- **Cabe:** furto de bens de pequeno valor (sem violência), descaminho até R$ 20.000 (Súmula STJ atualizada)\n'
'- **NÃO cabe:** crimes com violência, ameaça, agentes públicos, reincidência específica, crimes de roubo (Súmula 8 STJ), tráfico de drogas (STF — substância influente, mesmo em pequena quantidade)\n\n'
'### 5.4. Exclui a tipicidade\n\n'
'A bagatela exclui a **tipicidade material** — o fato é formalmente típico, mas materialmente atípico.\n\n'
'## 6. Princípio da Adequação Social\n\n'
'### 6.1. Conceito\n\n'
'Condutas **socialmente aceitas** e **toleradas** não devem ser tipificadas, ainda que formalmente correspondam a tipos previstos em lei.\n\n'
'### 6.2. Exemplos\n\n'
'- Furo de orelha em crianças (formalmente lesão corporal — não é punido)\n'
'- Trote tradicional em universitários\n'
'- Comércio de CD/DVD pirata (STF: NÃO se aplica — Súmula 502 STJ)\n\n'
'## 7. Princípio da Culpabilidade (Nullum Crimen Sine Culpa)\n\n'
'### 7.1. Conceito\n\n'
'Não há **pena sem culpabilidade**. O Estado só pode punir quem agiu com **dolo ou culpa** (responsabilidade subjetiva).\n\n'
'### 7.2. Vedação à responsabilidade objetiva penal\n\n'
'Diferentemente da responsabilidade civil objetiva (consagrada em diversas situações), no Direito Penal **vige a responsabilidade subjetiva absoluta**. Não há crime sem dolo ou culpa.\n\n'
'### 7.3. Versari in re illicita\n\n'
'Doutrina antiga que admitia responsabilização objetiva no Direito Penal. **Rejeitada** pela teoria moderna.\n\n'
'## 8. Princípio da Lesividade (Ofensividade)\n\n'
'### 8.1. Conceito\n\n'
'Só pode haver crime se houver **lesão ou perigo de lesão** a bem jurídico **alheio**.\n\n'
'### 8.2. Aplicação\n\n'
'- **Vedação ao crime sem lesividade:** auto-mutilação, posse de drogas para uso pessoal (Lei 11.343/06 art. 28 — STF reconheceu repercussão geral sobre constitucionalidade, RE 635.659)\n'
'- **Pensamento não é crime** (cogitatio non punitur)\n'
'- **Conduta interna não punível**\n\n'
'## 9. Princípio da Humanidade\n\n'
'### 9.1. Conceito\n\n'
'Vedação a **penas cruéis, desumanas, degradantes** (CF 5º, XLVII).\n\n'
'### 9.2. Penas vedadas (CF 5º, XLVII)\n\n'
'- De morte (salvo guerra declarada)\n'
'- De caráter perpétuo\n'
'- De trabalhos forçados\n'
'- De banimento\n'
'- Cruéis\n\n'
'## 10. Princípio da Proporcionalidade\n\n'
'### 10.1. Conceito\n\n'
'A pena deve ser **proporcional** à gravidade do crime. Decorre da CF 5º, XLVI (individualização da pena) e da própria justiça material.\n\n'
'### 10.2. Aplicação\n\n'
'- Vedação a penas excessivas\n'
'- Equilíbrio entre lesividade e sanção\n'
'- STF aplicou em diversos casos (HC sobre tráfico privilegiado)\n\n'
'## 11. Princípio da Individualização da Pena (CF 5º XLVI)\n\n'
'### 11.1. Conceito\n\n'
'A pena deve ser **individualizada** conforme:\n'
'- O autor\n'
'- A gravidade do fato\n'
'- As circunstâncias\n\n'
'### 11.2. Três momentos\n\n'
'**a) Legislativo:** lei define a pena cominada (mínimo e máximo)\n'
'**b) Judicial:** juiz aplica conforme arts. 59-68 do CP\n'
'**c) Executório:** execução conforme o caso concreto (LEP)\n\n'
'## 12. Princípio da Pessoalidade (Intranscendência) — CF 5º, XLV\n\n'
'A pena **não passa da pessoa** do condenado. A morte do réu extingue a punibilidade (CP 107, I). Mas obrigações civis (ressarcimento) podem ser cobradas dos sucessores até o limite da herança.\n\n'
'## 13. Princípio do Ne Bis in Idem\n\n'
'### 13.1. Conceito\n\n'
'Ninguém pode ser punido **duas vezes pelo mesmo fato**. Tem fundamento no Pacto de São José da Costa Rica (art. 8.4) e na doutrina.\n\n'
'### 13.2. Aplicação\n\n'
'- Vedação à dupla persecução\n'
'- Coisa julgada penal absolutória ou condenatória\n'
'- Reincidência: o STF (RE 453.000) manteve sua constitucionalidade, embora minoritariamente questionada\n\n'
'## 14. Princípio do Devido Processo Legal Substancial (CF 5º LIV)\n\n'
'O processo penal deve respeitar **direitos processuais e materiais** do acusado — incluindo contraditório, ampla defesa, presunção de inocência (CF 5º LVII).\n\n'
'## 15. Quadro-resumo\n\n'
'| Princípio | Síntese |\n'
'|---|---|\n'
'| Legalidade | Não há crime sem lei prévia |\n'
'| Anterioridade | Lei retroativa apenas se benéfica |\n'
'| Intervenção mínima | Ultima ratio + fragmentariedade |\n'
'| Insignificância | Lesão mínima exclui tipicidade material |\n'
'| Adequação social | Conduta tolerada não é crime |\n'
'| Culpabilidade | Não há pena sem dolo ou culpa |\n'
'| Lesividade | Só crime com lesão a bem alheio |\n'
'| Humanidade | Vedação a penas cruéis |\n'
'| Proporcionalidade | Pena adequada ao crime |\n'
'| Individualização | Pena conforme o caso |\n'
'| Pessoalidade | Pena não transmite |\n'
'| Ne bis in idem | Vedação à dupla punição |\n\n'
'## 16. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Medida provisória pode criar crime" ❌ — vedação expressa (CF 62 § 1º b)\n'
'- "Analogia in bonam partem é vedada" ❌ — vedação é apenas para prejudicar\n'
'- "Insignificância cabe em roubo" ❌ — só em furto sem violência (e nem sempre)\n'
'- "Adequação social aplica-se à pirataria" ❌ — Súmula 502 STJ\n'
'- "Pena pode ultrapassar a pessoa do condenado" ❌ — só obrigações civis até limite da herança\n'
'- "Cabe pena de morte por crime comum" ❌ — só em guerra declarada\n\n'
'## 17. Conclusão\n\n'
'Os princípios do Direito Penal são o **escudo do cidadão** contra o jus puniendi do Estado. Para concursos policiais, dominar legalidade (com seus 4 subprincípios), anterioridade com lei benéfica, intervenção mínima (com bagatela e adequação social), culpabilidade e humanidade é estratégia certa. Esses princípios fundamentam todas as discussões posteriores sobre tipicidade, ilicitude, culpabilidade e pena.\n',

  'Princípios do Direito Penal (garantias contra jus puniendi): (1) Legalidade (CF 5º XXXIX + CP 1º) — desdobramentos: reserva legal, anterioridade, taxatividade, vedação à analogia in malam partem; (2) Anterioridade — lei retroage só pra beneficiar (CF 5º XL); (3) Intervenção Mínima (ultima ratio) — fragmentariedade + subsidiariedade; (4) Insignificância (bagatela — STF HC 84.412): mínima ofensividade + ausência de periculosidade + reduzida reprovabilidade + inexpressividade da lesão (exclui tipicidade material); NÃO cabe em roubo/tráfico/violência; (5) Adequação Social (não em pirataria — Súmula 502 STJ); (6) Culpabilidade — vedada responsabilidade objetiva penal; (7) Lesividade — só crime com lesão a bem alheio; (8) Humanidade (CF 5º XLVII vedando morte salvo guerra, perpétua, trabalhos forçados, banimento, cruéis); (9) Proporcionalidade; (10) Individualização (CF 5º XLVI); (11) Pessoalidade (CF 5º XLV — não transmite ao herdeiro salvo obrigações civis); (12) Ne bis in idem.'
