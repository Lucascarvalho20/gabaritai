'**d) Teoria Social:** conduta é comportamento humano socialmente relevante.\n\n'
'**Teoria adotada pelo CP brasileiro: FINALISTA** (consagrada pela reforma de 1984 — Lei 7.209/84).\n\n'
'### 2.3. Conduta omissiva\n\n'
'A conduta pode ser **omissão** — não fazer algo a que se está obrigado.\n\n'
'**a) Omissão própria:** o tipo descreve a omissão (omissão de socorro — CP 135).\n\n'
'**b) Omissão imprópria (comissão por omissão):** o resultado decorre da omissão de quem tinha **dever jurídico** de agir. Ex: mãe que não alimenta filho que morre de fome.\n\n'
