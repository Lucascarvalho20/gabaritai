'a) Tenha por lei obrigação de cuidado, proteção ou vigilância (pais, médicos)\n'
'b) De outra forma assumiu a responsabilidade de impedir o resultado (babá, salva-vidas)\n'
'c) Com seu comportamento anterior, criou o risco da ocorrência do resultado (quem empurra alguém na piscina é obrigado a salvar)\n\n'
'### 2.4. Ausência de conduta\n\n'
'Não há conduta penalmente relevante em:\n\n'
'- **Atos reflexos** (reação involuntária)\n'
'- **Sonambulismo**\n'
'- **Estados de inconsciência** (epilepsia em curso)\n'
'- **Hipnose** (controvertido — depende do caso)\n'
'- **Coação física irresistível** (vis absoluta)\n\n'
'**Diferença importante:**\n'
'- **Coação física (vis absoluta):** exclui a **conduta** (não há ação voluntária)\n'
