SELECT upsert_material(
  'direito-penal',
  'Aplicação da Lei Penal no Tempo',
  'Aplicação da Lei Penal no Tempo: irretroatividade, retroatividade benéfica (CP 2º-4º)',

E'# Aplicação da Lei Penal no Tempo\n\n'
'## 1. Visão geral\n\n'
'A aplicação da lei penal no tempo trata da **eficácia temporal** da norma penal: quando uma nova lei é editada, **quais fatos ela alcança**? E quando o crime ocorre, **qual lei se aplica**?\n\n'
'É tema crucial porque envolve **segurança jurídica**, **garantia do cidadão** contra a retroatividade prejudicial e a **possibilidade de beneficiar** o réu com lei posterior mais favorável.\n\n'
'## 2. Princípios fundamentais\n\n'
'### 2.1. Tempus regit actum\n\n'
'**Regra geral:** aplica-se ao fato a **lei vigente no momento de sua prática**.\n\n'
'### 2.2. Irretroatividade da lei penal (CF 5º XL)\n\n'
'**A lei penal NÃO retroage**, salvo para beneficiar o réu.\n\n'
'### 2.3. Retroatividade benéfica\n\n'
'**A lei posterior mais favorável retroage**, aplicando-se inclusive a fatos anteriores e a processos em andamento, e até mesmo a decisões transitadas em julgado (CP 2º, parágrafo único).\n\n'
'## 3. CP arts. 1º a 4º\n\n'
'### 3.1. CP art. 1º — Legalidade e anterioridade\n\n'
'*"Não há crime sem lei anterior que o defina. Não há pena sem prévia cominação legal."*\n\n'
'### 3.2. CP art. 2º — Lei penal no tempo\n\n'
'**Caput:** *"Ninguém pode ser punido por fato que lei posterior deixa de considerar crime, cessando em virtude dela a execução e os efeitos penais da sentença condenatória."*\n\n'
'**Parágrafo único:** *"A lei posterior, que de qualquer modo favorecer o agente, aplica-se aos fatos anteriores, ainda que decididos por sentença condenatória transitada em julgado."*\n\n'
'### 3.3. CP art. 3º — Lei excepcional ou temporária\n\n'
'*"A lei excepcional ou temporária, embora decorrido o período de sua duração ou cessadas as circunstâncias que a determinaram, aplica-se ao fato praticado durante sua vigência."*\n\n'
'### 3.4. CP art. 4º — Tempo do crime\n\n'
'*"Considera-se praticado o crime no momento da ação ou omissão, ainda que outro seja o momento do resultado."*\n\n'
'**Teoria adotada: ATIVIDADE.**\n\n'
'## 4. Fenômenos da sucessão de leis no tempo\n\n'
'### 4.1. Abolitio criminis (CP 2º caput)\n\n'
'**Conceito:** lei posterior **descriminaliza** o fato — deixa de ser crime.\n\n'
'**Consequências:**\n'
'- Cessa a execução da pena\n'
'- Apaga os efeitos penais da sentença (folha de antecedentes, reincidência)\n'
'- **Subsistem os efeitos civis** (ressarcimento de danos)\n\n'
'**Exemplo:** adultério foi descriminalizado pela Lei 11.106/05. Pessoas condenadas por adultério tiveram a execução cessada.\n\n'
'### 4.2. Novatio legis in mellius (lex mitior)\n\n'
'**Conceito:** lei posterior **favorece o réu** — reduz pena, abranda regime, introduz causa de redução, etc.\n\n'
'**Aplicação:** retroage, alcançando até processos com **trânsito em julgado**.\n\n'
'**Exemplo:** Lei 12.015/09 reduziu a pena do estupro de vulnerável em algumas hipóteses; aplicou-se retroativamente.\n\n'
'### 4.3. Novatio legis in pejus (lex gravior)\n\n'
'**Conceito:** lei posterior **prejudica o réu** — aumenta pena, agrava regime, etc.\n\n'
'**Aplicação:** **NÃO retroage**. Aplica-se apenas a fatos cometidos após sua vigência.\n\n'
'### 4.4. Novatio legis incriminadora\n\n'
'**Conceito:** lei posterior **cria** crime que antes não existia (nova tipificação).\n\n'
'**Aplicação:** **NÃO retroage**. Aplica-se apenas a fatos cometidos após sua vigência.\n\n'
'**Exemplo:** Lei 12.737/12 (Carolina Dieckmann) criou o crime de invasão de dispositivo informático — não atinge invasões anteriores.\n\n'
'## 5. Combinação de leis (lex tertia)\n\n'
'### 5.1. Questão controvertida\n\n'
'Pode o juiz **combinar partes** de duas leis (uma antiga e uma nova), aproveitando o que cada uma tem de melhor para o réu?\n\n'
'### 5.2. STF — posição majoritária\n\n'
'**STF (RE 596.152 — Tema 142, 2013):** **NÃO se admite combinação de leis** — formaria-se uma "terceira lei" que não foi criada pelo legislador, violando o princípio da separação dos poderes.\n\n'
'**Súmula 501 STJ:** *"É cabível a aplicação retroativa da Lei nº 11.343/2006, desde que o resultado da incidência das suas disposições, na íntegra, seja mais favorável ao réu do que o advindo da aplicação da Lei nº 6.368/1976, sendo vedada a combinação de leis."*\n\n'
'### 5.3. Solução\n\n'
'O juiz deve aplicar uma das leis **na íntegra** — a que, no resultado final, for mais favorável.\n\n'
'## 6. Lei intermediária (lex intermedia)\n\n'
'### 6.1. Conceito\n\n'
'Lei que **não estava em vigor** nem no momento do fato nem no momento do julgamento, mas vigorou entre eles, e é a mais benéfica.\n\n'
'### 6.2. Aplicação\n\n'
'Aplica-se a **lei intermediária** se for a mais favorável, pelo princípio da retroatividade benéfica.\n\n'
'**Exemplo:** crime cometido em 2010 (lei A). Em 2015 entrou em vigor lei B (mais branda). Em 2020 entrou em vigor lei C (mais rigorosa que B mas mais branda que A). No julgamento em 2022, aplica-se a lei B (mais favorável).\n\n'
'## 7. Lei excepcional ou temporária (CP 3º)\n\n'
'### 7.1. Conceitos\n\n'
'**Lei excepcional:** editada para **situações de emergência** (guerra, calamidade), com vigência atrelada à duração da situação.\n\n'
'**Lei temporária:** com **prazo certo de vigência** previsto no próprio texto legal.\n\n'
'### 7.2. Característica especial: ultraatividade\n\n'
'Mesmo após o **fim de sua vigência**, essas leis continuam a ser aplicadas aos fatos praticados durante sua vigência.\n\n'
'**Razão:** a finalidade da lei seria frustrada se a impunidade fosse a regra após o fim da vigência.\n\n'
'### 7.3. STF (RE 168.929, etc.)\n\n'
'Confirmou a constitucionalidade do art. 3º.\n\n'
'## 8. Tempo do crime (CP 4º)\n\n'
'### 8.1. Teorias\n\n'
'**a) Teoria da Atividade:** o crime ocorre no momento da **ação ou omissão**, independentemente do momento do resultado.\n\n'
'**b) Teoria do Resultado:** o crime ocorre no momento do **resultado**.\n\n'
'**c) Teoria Mista (Ubiquidade):** o crime ocorre em ambos os momentos.\n\n'
'### 8.2. Teoria adotada pelo CP: ATIVIDADE\n\n'
'**CP art. 4º:** *"Considera-se praticado o crime no momento da ação ou omissão, ainda que outro seja o momento do resultado."*\n\n'
'### 8.3. Exemplo\n\n'
'Pessoa atira na vítima em 31/12/2024 (Lei A vigente). A vítima morre em 02/01/2025 (Lei B vigente, mais grave). Aplica-se a **Lei A** (do momento da conduta).\n\n'
'### 8.4. Implicações\n\n'
'- Determina a lei aplicável\n'
'- Determina a maioridade (idade no momento da ação)\n'
'- Determina a imputabilidade (insanidade no momento do ato)\n\n'
'## 9. Tempo do crime em crimes específicos\n\n'
'### 9.1. Crimes permanentes\n\n'
'O crime se prolonga no tempo (sequestro, cárcere privado, associação criminosa). **Súmula 711 STF:** *"A lei penal mais grave aplica-se ao crime continuado ou ao crime permanente, se a sua vigência é anterior à cessação da continuidade ou da permanência."*\n\n'
'### 9.2. Crimes continuados\n\n'
'Vários crimes da mesma espécie em condições que os tornem continuação um do outro (CP 71). Aplica-se a Súmula 711 STF.\n\n'
'### 9.3. Crimes habituais\n\n'
'Exigem reiteração (exercício ilegal da medicina). A lei mais grave que vigora durante a habitualidade pode ser aplicada.\n\n'
'### 9.4. Crimes a distância\n\n'
'Ação em um momento, resultado em outro. Aplica-se a teoria da atividade (CP 4º).\n\n'
'## 10. Vacatio legis e aplicação\n\n'
'### 10.1. Vacatio legis\n\n'
'Período entre **publicação** e **vigência** da lei. Em regra, **45 dias** se não houver previsão expressa.\n\n'
'### 10.2. Aplicação\n\n'
'**Lei na vacatio legis:** ainda não está em vigor — não pode incriminar fatos atuais. Mas, se for **mais benéfica** e o legislador deixou prazo de adaptação, a doutrina majoritária e o STJ admitem aplicação imediata (em casos específicos).\n\n'
'## 11. Reincidência e abolitio criminis\n\n'
'**Súmula STJ 220:** *"A reincidência não influi no prazo da prescrição da pretensão punitiva."* (Aplicável após abolitio criminis: o efeito penal da reincidência se apaga.)\n\n'
'A abolitio criminis **apaga totalmente** os efeitos penais da condenação — inclusive a possibilidade de gerar reincidência.\n\n'
'## 12. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Lei penal pode retroagir para prejudicar" ❌\n'
'- "Abolitio criminis apenas cessa a execução" ❌ — apaga TODOS os efeitos penais\n'
'- "Combinação de leis é permitida" ❌ — STF e STJ vedam\n'
'- "Lei intermediária não se aplica" ❌ — aplica se mais benéfica\n'
