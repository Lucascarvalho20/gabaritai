'## 2. Conduta\n\n'
'### 2.1. Conceito\n\n'
'**Conduta** é a **ação ou omissão consciente e voluntária** dirigida a um fim (teoria finalista) ou produtora de um resultado (teoria causalista).\n\n'
'### 2.2. Teorias da conduta\n\n'
'**a) Teoria Causalista (clássica — Liszt-Beling):** conduta como movimento corporal voluntário causador de modificação no mundo exterior. **Dolo e culpa eram considerados na culpabilidade**, não na conduta.\n\n'
