'- Crimes contra a coletividade\n\n'
'## 8. Excesso (CP 23, parágrafo único)\n\n'
'### 8.1. Conceito\n\n'
'**CP art. 23, parágrafo único:** *"O agente, em qualquer das hipóteses deste artigo, responderá pelo excesso doloso ou culposo."*\n\n'
'### 8.2. Tipos\n\n'
'**a) Excesso doloso:** o agente quer ir além do necessário\n'
'**b) Excesso culposo:** o agente perde o controle\n'
'**c) Excesso acidental:** decorrente de circunstâncias imprevisíveis (controvertido)\n\n'
'### 8.3. Responsabilização\n\n'
'O agente responde pelo **excesso**, não pelo crime original (que estava justificado até o limite).\n\n'
'## 9. Causas supralegais\n\n'
'Reconhecidas pela jurisprudência além das previstas no CP:\n\n'
'- **Consentimento do ofendido**\n'
'- **Adequação social** (em parte; alguns colocam na tipicidade)\n'
'- **Inexigibilidade de conduta diversa** (na culpabilidade)\n\n'
'## 10. Descriminantes putativas (CP 20 § 1º)\n\n'
'### 10.1. Conceito\n\n'
'**Erro sobre a existência da causa de exclusão da ilicitude.** O agente acredita, por engano, estar em situação que o autoriza.\n\n'
'### 10.2. Espécies\n\n'
'**a) Erro sobre os pressupostos fáticos** (acredita ser legítima defesa, mas não é): exclui o **dolo** (responde por culpa, se houver previsão culposa).\n\n'
'**b) Erro sobre a existência ou limites da norma** (acredita que está autorizado por norma que não existe): exclui a **culpabilidade** se o erro for inevitável; se evitável, atenua a pena.\n\n'
'## 11. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
