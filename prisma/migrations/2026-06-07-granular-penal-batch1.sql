'**CP art. 23:** *"Não há crime quando o agente pratica o fato:"*\n\n'
'**I — em estado de necessidade**\n'
'**II — em legítima defesa**\n'
'**III — em estrito cumprimento de dever legal ou no exercício regular de direito**\n\n'
'## 3. Estado de Necessidade (CP 24)\n\n'
'### 3.1. Conceito\n\n'
'**CP art. 24:** *"Considera-se em estado de necessidade quem pratica o fato para salvar de perigo atual, que não provocou por sua vontade, nem podia de outro modo evitar, direito próprio ou alheio, cujo sacrifício, nas circunstâncias, não era razoável exigir-se."*\n\n'
'### 3.2. Requisitos\n\n'
'**1. Perigo atual (não futuro nem passado)**\n'
'**2. Perigo não provocado por vontade do agente**\n'
'**3. Inevitabilidade do perigo por outros meios**\n'
'**4. Direito próprio ou alheio em risco**\n'
'**5. Inexigibilidade do sacrifício** do bem sacrificado\n'
'**6. Conhecimento da situação justificante** (elemento subjetivo)\n\n'
'### 3.3. Exemplos clássicos\n\n'
'- Naufrágio: um náufrago empurra outro do único bote (matar para salvar a própria vida)\n'
'- Incêndio: rompe janela alheia para salvar pessoa\n'
'- Furto famélico: pessoa em extrema fome subtrai alimento\n\n'
'### 3.4. Distinção: agressivo x defensivo\n\n'
'**a) Estado de necessidade agressivo:** o agente atinge bem de pessoa **estranha** ao perigo (B foge do incêndio e quebra vidraça de C).\n\n'
'**b) Estado de necessidade defensivo:** o agente atinge bem da própria **fonte do perigo** (B mata o cão de C que o atacava).\n\n'
'**Indenização:**\n'
'- **Defensivo:** não há indenização (atacou-se a fonte do perigo)\n'
'- **Agressivo:** há indenização à pessoa estranha (mas o agente tem direito de regresso contra quem causou o perigo)\n\n'
'### 3.5. Teoria adotada\n\n'
'**Teoria Unitária (CP):** estado de necessidade é **sempre excludente de ilicitude** (não há distinção entre justificante e exculpante no CP brasileiro).\n\n'
'## 4. Legítima Defesa (CP 25)\n\n'
'### 4.1. Conceito\n\n'
'**CP art. 25:** *"Entende-se em legítima defesa quem, usando moderadamente dos meios necessários, repele injusta agressão, atual ou iminente, a direito seu ou de outrem."*\n\n'
'### 4.2. Requisitos\n\n'
'**1. Agressão injusta** (não autorizada pelo direito)\n'
'**2. Agressão atual ou iminente** (não passada)\n'
'**3. Direito próprio ou alheio**\n'
'**4. Uso dos meios necessários**\n'
'**5. Moderação** no uso dos meios\n'
'**6. Conhecimento da situação justificante** (elemento subjetivo)\n\n'
'### 4.3. Detalhamento\n\n'
'**Agressão injusta:** humana, ilícita. Não cabe legítima defesa contra ataques de animais (sem dono) — aplica-se estado de necessidade.\n\n'
'**Agressão atual:** está acontecendo. **Iminente:** prestes a acontecer.\n\n'
'**Não cabe legítima defesa contra agressão passada** — seria vingança.\n\n'
'**Meios necessários:** os disponíveis ao agente para repelir a agressão. Não precisam ser proporcionais ao da agressão (se só tem arma de fogo e o agressor tem faca, pode usar a arma).\n\n'
'**Moderação:** usar o mínimo necessário. O excesso na defesa configura **excesso punível**.\n\n'
'### 4.4. Espécies\n\n'
'**a) Legítima defesa própria:** defesa de direito próprio\n'
'**b) Legítima defesa de terceiro:** defesa de direito alheio\n'
'**c) Legítima defesa real:** efetivamente houve agressão\n'
'**d) Legítima defesa putativa:** o agente acredita estar sendo agredido, mas não está (descriminante putativa — CP 20 § 1º)\n'
'**e) Legítima defesa sucessiva:** quem foi inicialmente agressor, ao excessar a vítima, pode ser legitimamente defendido\n\n'
'### 4.5. Não cabe legítima defesa contra:\n\n'
'- Legítima defesa real (não há "legítima defesa contra legítima defesa")\n'
'- Estado de necessidade real\n'
'- Estrito cumprimento de dever legal\n'
'- Exercício regular de direito\n\n'
'**Razão:** essas são ações lícitas — não constituem agressão injusta.\n\n'
'**Cabe** legítima defesa contra **legítima defesa putativa** (porque, em si, é uma agressão injusta).\n\n'
'## 5. Estrito Cumprimento de Dever Legal\n\n'
'### 5.1. Conceito\n\n'
'Praticar o fato típico no **estrito cumprimento de dever legal** — quando a lei impõe o ato.\n\n'
'### 5.2. Exemplos\n\n'
'- Policial que efetua prisão em flagrante\n'
'- Soldado que dispara em combate\n'
'- Oficial de justiça que penhora bem\n'
'- Carcereiro que mantém preso recolhido\n\n'
'### 5.3. Requisitos\n\n'
'1. Existir **dever legal** (lei, regulamento)\n'
'2. Estrito cumprimento (sem excesso)\n'
'3. Conhecimento da situação justificante\n\n'
'### 5.4. Excesso\n\n'
'Se o agente extrapola o necessário, responde por **excesso** (punível). Ex: policial que efetua prisão e bate no preso indefeso.\n\n'
'## 6. Exercício Regular de Direito\n\n'
'### 6.1. Conceito\n\n'
'Praticar o fato típico no **exercício regular de direito reconhecido pelo ordenamento**.\n\n'
'### 6.2. Exemplos\n\n'
'- **Lutas esportivas autorizadas:** boxer, MMA. As lesões são exercício regular do direito de praticar esportes regulamentados.\n'
'- **Operações cirúrgicas:** médico que pratica cirurgia (lesão corporal) está no exercício regular do direito.\n'
'- **Cobrança de dívida:** credor que cobra (sem excesso)\n'
'- **Furto em legítima defesa do patrimônio:** quem subtrai bem para evitar dano maior\n\n'
'### 6.3. Requisitos\n\n'
'1. Existir **direito** legalmente reconhecido\n'
'2. Exercício **regular** (sem abuso)\n'
'3. Conhecimento da situação justificante\n\n'
'## 7. Consentimento do Ofendido\n\n'
'### 7.1. Status\n\n'
'**Não previsto expressamente** no CP como excludente, mas reconhecido pela doutrina e jurisprudência como **causa supralegal de exclusão da ilicitude**.\n\n'
'### 7.2. Requisitos\n\n'
'1. **Bem jurídico disponível** (não vale para bens indisponíveis — vida)\n'
'2. **Consentimento válido** (capacidade, livre, consciente)\n'
'3. **Anterior ou simultâneo** à conduta\n\n'
'### 7.3. Aplicação\n\n'
'- Lesão corporal leve consentida (tatuagem, piercing)\n'
'- Dano consentido em propriedade alheia\n'
'- Subtração com permissão\n\n'
'**NÃO se aplica:**\n'
