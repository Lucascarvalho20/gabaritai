'## 10. Conclusão\n\n'
'O direito de greve do servidor é exemplo de **construção jurisprudencial** — sem lei específica, o STF aplicou analogicamente a Lei 7.783/89. Para concursos, dominar: (a) a omissão legislativa e a solução do STF (MI 670/708/712); (b) a vedação a militares e à segurança pública (Tema 541); (c) a possibilidade de desconto nos vencimentos; (d) a competência da Justiça Comum. Esses são os pontos certeiros em prova.\n',

