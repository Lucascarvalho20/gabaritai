'**IX — Valer-se do cargo para lograr proveito pessoal ou de outrem** em detrimento da dignidade da função pública\n\n'
'**X — Participar de gerência ou administração de sociedade privada, personificada ou não personificada, exercer o comércio, exceto na qualidade de acionista, cotista ou comanditário**\n\n'
'**XI — Atuar, como procurador ou intermediário, junto a repartições públicas**, salvo quando se tratar de benefícios previdenciários ou assistenciais de parentes até o segundo grau, e de cônjuge ou companheiro\n\n'
'**XII — Receber propina, comissão, presente ou vantagem** de qualquer espécie, em razão de suas atribuições\n\n'
'**XIII — Aceitar comissão, emprego ou pensão de estado estrangeiro**\n\n'
'**XIV — Praticar usura sob qualquer de suas formas**\n\n'
'**XV — Proceder de forma desidiosa** (negligência)\n\n'
'**XVI — Utilizar pessoal ou recursos materiais da repartição em serviços ou atividades particulares**\n\n'
'**XVII — Cometer a outro servidor atribuições estranhas ao cargo** que ocupa, exceto em situações de emergência e transitórias\n\n'
'**XVIII — Exercer quaisquer atividades que sejam incompatíveis com o exercício do cargo ou função e com o horário de trabalho**\n\n'
'**XIX — Recusar-se a atualizar seus dados cadastrais** quando solicitado\n\n'
'### 3.2. Classificação das proibições (art. 132)\n\n'
'Algumas proibições, quando descumpridas, levam à **demissão** (art. 132):\n\n'
'- Itens IX (proveito pessoal)\n'
'- XI (intermediário)\n'
'- XII (propina)\n'
'- XIII (emprego estrangeiro)\n'
'- XIV (usura)\n'
'- XV (desídia)\n'
'- XVI (pessoal/recursos)\n'
'- XVII (acumulação)\n\n'
'## 4. Acumulação de cargos (CF art. 37, XVI)\n\n'
'### 4.1. Vedação geral\n\n'
'A regra constitucional é a **vedação à acumulação remunerada de cargos públicos**, salvo nas hipóteses excepcionais previstas.\n\n'
'### 4.2. Hipóteses permitidas (CF 37, XVI)\n\n'
'**Cumulativamente exige:**\n'
'- **Compatibilidade de horários**\n'
'- **Sujeição ao teto remuneratório** (CF 37, XI)\n\n'
'**Combinações permitidas:**\n\n'
'a) **Dois cargos de professor**\n'
'b) **Um cargo de professor com outro técnico ou científico**\n'
'c) **Dois cargos ou empregos privativos de profissionais de saúde**, com profissões regulamentadas\n\n'
'### 4.3. Conceito de "cargo técnico ou científico"\n\n'
'**STF:** cargo que exige **conhecimento técnico especializado** e **diploma de nível superior** ou nível médio técnico. Exemplos: engenheiro, médico, contador, biólogo, técnico em enfermagem, técnico em informática.\n\n'
'**NÃO** se considera técnico:\n'
'- Funções administrativas comuns (analista, auxiliar)\n'
'- Polícia (a CF veda expressamente a acumulação de cargos policiais)\n\n'
'### 4.4. Inacumulabilidade em cargos policiais\n\n'
'**Polícia Federal, Polícia Rodoviária Federal, Polícias Civis e Militares:** cargos **inacumuláveis** com qualquer outro cargo público, salvo se for um dos casos permitidos (professor + policial-professor, médico + polícia médica em algumas situações específicas — análise caso a caso pelo STJ).\n\n'
'### 4.5. Acumulação ilegal\n\n'
'**Descoberta a acumulação ilegal:**\n'
'- Servidor é notificado a optar por um dos cargos em **10 dias**\n'
'- Se não optar, **abre PAD sumário** (art. 133)\n'
'- Resultado: **exoneração de ofício do cargo posterior** (mantém o anterior) ou **demissão** se houver má-fé\n\n'
'### 4.6. Acumulação x aposentadoria\n\n'
'**Aposentado em um cargo + ativo em outro:** permitida desde que respeite as hipóteses de acumulação (professor com professor; saúde com saúde, etc.).\n\n'
'**Dois aposentados:** permitida nas hipóteses do art. 37, XVI.\n\n'
'## 5. Nepotismo (Súmula Vinculante 13)\n\n'
'### 5.1. Conceito\n\n'
'Nomeação de parentes para cargos em comissão ou funções de confiança.\n\n'
'### 5.2. SV 13 STF\n\n'
'*"A nomeação de cônjuge, companheiro ou parente em linha reta, colateral ou por afinidade, até o terceiro grau, inclusive, da autoridade nomeante ou de servidor da mesma pessoa jurídica investido em cargo de direção, chefia ou assessoramento, para o exercício de cargo em comissão ou de confiança ou, ainda, de função gratificada na administração pública direta e indireta em qualquer dos Poderes da União, dos Estados, do Distrito Federal e dos Municípios, compreendido o ajuste mediante designações recíprocas, viola a Constituição Federal."*\n\n'
'### 5.3. Abrangência\n\n'
'- **Parentes até 3º grau**\n'
'- **Inclui afinidade e colaterais**\n'
'- **Inclui "nepotismo cruzado"** (ajustes recíprocos entre autoridades)\n'
'- **Em qualquer Poder** (Executivo, Legislativo, Judiciário)\n\n'
'### 5.4. Exceção\n\n'
'**Agentes políticos** (Ministros, Secretários) — STF tem entendido que a SV 13 não se aplica integralmente a eles, em razão da natureza política da função.\n\n'
'## 6. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Servidor deve cumprir todas as ordens superiores" ❌ — ressalvadas as manifestamente ilegais\n'
'- "Policial pode acumular cargo de policial" ❌\n'
'- "Acumulação permite 3 cargos de professor" ❌ — máximo 2\n'
'- "Nepotismo é permitido entre Ministros" — em parte; agentes políticos têm regime especial\n'
'- "Optar pelo cargo encerra o processo de acumulação" ❌ — pode haver ressarcimento\n'
'- "Compatibilidade de horários autoriza acumular cargos não previstos" ❌\n'
'- "Receber propina é apenas crime, não infração administrativa" ❌ — ambos\n\n'
'## 7. Conclusão\n\n'
'O regime de deveres e proibições é o **escudo ético** do servidor público. Para concursos, dominar a lista do art. 116 (deveres) e art. 117 (proibições), além das regras de acumulação (CF 37, XVI) e da Súmula Vinculante 13 (nepotismo), é essencial. As proibições mais graves (propina, desídia, atuação como intermediário) levam à demissão e podem configurar improbidade e crime.\n',

  'Deveres (Lei 8.112/90 art. 116, 12 incisos): zelo, lealdade, observar normas, cumprir ordens superiores (salvo manifestamente ilegais), atender com presteza, comunicar irregularidades, zelar pelo patrimônio, sigilo, moralidade, assiduidade, urbanidade, representar contra abusos. Proibições (art. 117, 19 incisos): ausência sem autorização, retirar documentos, recusar fé, manifestação política no recinto, NEPOTISMO (SV 13 — parentes até 3º grau), proveito pessoal, comércio/gerência, intermediário, PROPINA, comissão estrangeira, usura, desídia, recursos para particulares. Acumulação (CF 37 XVI): vedada salvo professor+professor, professor+técnico/científico, saúde+saúde (com compatibilidade + teto). Policial: inacumulável. Acumulação ilegal = exoneração após PAD sumário.'
