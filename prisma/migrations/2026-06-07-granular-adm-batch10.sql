E'# Cargo, Emprego e Função Pública\n\n'
'## 1. Visão geral\n\n'
'As três figuras — **cargo público, emprego público e função pública** — são as formas pelas quais o indivíduo vincula-se à Administração Pública para prestar serviços. Cada uma tem **regime jurídico próprio**, com implicações em direitos, deveres, responsabilidade e estabilidade.\n\n'
