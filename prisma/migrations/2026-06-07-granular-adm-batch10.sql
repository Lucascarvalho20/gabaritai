'- Improbidade administrativa\n'
'- Insubordinação grave\n'
'- Ofensa física\n'
'- Aplicação irregular de dinheiros públicos\n'
'- Revelação de segredo\n'
'- Lesão aos cofres públicos\n'
'- Corrupção\n'
'- Acumulação ilegal de cargos\n'
'- Transgressão dos arts. 117 (proibições graves)\n\n'
'### 4.3. Procedimento\n\n'
'**PAD** (Processo Administrativo Disciplinar) com **ampla defesa** (material 1 do Batch 8).\n\n'
'### 4.4. Efeitos\n\n'
'- Perda do cargo\n'
'- Em alguns casos, **inabilitação para nova investidura por 5 anos** (art. 137, parágrafo único)\n'
