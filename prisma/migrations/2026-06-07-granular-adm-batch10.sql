'- Publicação no DOU\n'
'- Prazo de comparecimento ao novo local\n\n'
'## 7. Redistribuição (art. 37)\n\n'
'### 7.1. Conceito\n\n'
'**Deslocamento do cargo de provimento efetivo** (ocupado ou não) de um **órgão para outro órgão** do mesmo Poder, com prévia apreciação do órgão central do SIPEC.\n\n'
