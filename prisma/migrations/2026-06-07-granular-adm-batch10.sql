'### 3.1. Conceito\n\n'
'**Dever de reparar o dano** causado pelo servidor a:\n\n'
'a) **Terceiros** (particulares) — responsabilidade primária do Estado, com regresso contra o servidor\n'
'b) **Própria Administração** — responsabilidade direta\n\n'
