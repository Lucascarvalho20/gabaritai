'| Hipóteses | Pedido, fim de estágio, não comparecimento | Faltas graves (art. 132) |\n'
'| Procedimento | Ato simples | PAD com ampla defesa |\n'
'| Efeitos | Pode ser reinvestido | Pode haver inabilitação |\n\n'
'## 4. Demissão\n\n'
'### 4.1. Conceito\n\n'
'**Penalidade disciplinar** aplicada ao servidor que comete infração grave. É a **mais grave** das sanções funcionais.\n\n'
'### 4.2. Hipóteses (Lei 8.112/90 art. 132)\n\n'
