'## 9. Cessão (art. 93)\n\n'
'### 9.1. Conceito\n\n'
'**Disposição do servidor** para outro órgão ou entidade dos Poderes da União, dos Estados, do DF e dos Municípios.\n\n'
'### 9.2. Hipóteses\n\n'
'- Para exercício de cargo em comissão ou função de confiança\n'
'- Em casos previstos em leis específicas\n\n'
'### 9.3. Ônus\n\n'
'**Regra (Lei 8.112 art. 93, § 1º):**\n'
'- Em geral, **ônus do cessionário** (quem recebe paga)\n'
'- Mas para cargos de natureza especial, ônus do cedente\n\n'
'## 10. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Exoneração é punição" ❌ — não é\n'
'- "Demissão é o mesmo que exoneração" ❌\n'
'- "Cargo em comissão exonerado por motivos políticos não cabe ação" ❌ — teoria dos motivos determinantes\n'
