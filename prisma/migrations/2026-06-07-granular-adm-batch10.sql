'4. **Readaptação** (no cargo de origem — se o servidor for readaptado a outro)\n'
'5. **Aposentadoria**\n'
'6. **Posse em outro cargo inacumulável**\n'
'7. **Falecimento**\n\n'
'## 3. Exoneração (arts. 34-35)\n\n'
'### 3.1. Conceito\n\n'
'**Desligamento do servidor sem caráter de punição**. Não é castigo, mas perda do vínculo por outros motivos.\n\n'
'### 3.2. Modalidades\n\n'
'**a) Exoneração de ofício (art. 34, II):**\n'
'- Não habilitação em estágio probatório\n'
'- Não comparecimento ao exercício no prazo\n'
'- Não posse no prazo (mais precisamente: tornar sem efeito a nomeação)\n'
'- Excesso de despesa pessoal (CF 169 § 4º)\n\n'
'**b) Exoneração a pedido (art. 34, I):**\n'
'- Manifestação do servidor de deixar o cargo\n'
'- Forma escrita\n'
'- Não pode ser feita quando em pendência de processo disciplinar (para evitar fuga de punição)\n\n'
'**c) Exoneração de cargo em comissão (art. 35):**\n'
'- **Ad nutum** — discricionária da autoridade\n'
'- Sem motivação obrigatória, em regra (mas STF tem temperado por teoria dos motivos determinantes)\n'
'- A pedido do ocupante também\n\n'
