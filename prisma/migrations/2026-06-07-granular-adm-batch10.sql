'## 1. Visão geral\n\n'
'A Lei 8.112/90 estabelece **três regimes simultâneos** de responsabilidade do servidor:\n\n'
'1. **Civil** (reparação patrimonial)\n'
'2. **Penal** (sanção criminal)\n'
'3. **Administrativa** (sanção disciplinar)\n\n'
