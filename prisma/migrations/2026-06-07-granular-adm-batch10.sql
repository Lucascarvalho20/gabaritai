'| Aspecto | Remoção | Redistribuição |\n'
'|---|---|---|\n'
'| O que se desloca | Servidor | Cargo (e servidor que o ocupa) |\n'
'| Mudança de órgão | Não | Sim |\n'
'| Vinculação | Mesmo quadro | Cargo migra para outro órgão |\n\n'
'## 8. Substituição (arts. 38-39)\n\n'
'### 8.1. Conceito\n\n'
'**Exercício temporário** das atribuições de outro cargo, em razão de ausência ou impedimento do titular.\n\n'
'### 8.2. Modalidades\n\n'
'**a) Automática:** previamente designado (suplente).\n'
'**b) Designada:** por ato específico em caso concreto.\n\n'
'### 8.3. Características\n\n'
