'### 6.2. Modalidades\n\n'
'**a) De ofício** (art. 36, I):\n'
'- Interesse da Administração\n'
'- Necessidade do serviço\n\n'
'**b) A pedido, a critério da Administração** (art. 36, II):\n'
'- Servidor solicita; concessão é discricionária\n\n'
