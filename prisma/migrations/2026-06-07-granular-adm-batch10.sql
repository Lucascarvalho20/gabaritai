'## 2. Fundamento normativo\n\n'
'- **CF arts. 37 a 41:** disciplina geral dos servidores\n'
'- **CF art. 39, § 4º:** subsídio (parcela única)\n'
'- **Lei 8.112/90:** Estatuto dos Servidores Civis da União\n'
'- **CLT (Decreto-Lei 5.452/43):** rege empregados públicos\n'
'- **Leis específicas:** carreiras especiais (Magistratura, MP, Defensoria, Polícia Federal, etc.)\n\n'
'## 3. Cargo Público\n\n'
'### 3.1. Conceito\n\n'
'Cargo público é o **conjunto de atribuições e responsabilidades** atribuídas, por lei, a um servidor, organizadas em uma estrutura de **carreira**, com **denominação própria** e **número certo**, retribuído pelo Estado.\n\n'
'**Lei 8.112/90 art. 3º:** *"Cargo público é o conjunto de atribuições e responsabilidades previstas na estrutura organizacional que devem ser cometidas a um servidor."*\n\n'
'### 3.2. Características\n\n'
'- **Criado por lei** específica\n'
'- **Acessível por concurso público** (regra)\n'
'- Pode ser **efetivo** ou **em comissão**\n'
'- Regime estatutário (legal, não contratual)\n'
'- **Direitos e deveres** previstos em lei (não em contrato)\n\n'
'### 3.3. Classificações\n\n'
'**a) Quanto ao provimento:**\n'
'- **Cargo efetivo:** provimento por concurso, sujeito a estabilidade\n'
'- **Cargo em comissão:** livre nomeação e exoneração (CF 37, II)\n'
'- **Cargo vitalício:** Magistratura, MP, Tribunais de Contas — garantia maior que a estabilidade\n\n'
'**b) Quanto à estrutura:**\n'
'- **De carreira:** integra hierarquia (analista, técnico)\n'
'- **Isolado:** sem vinculação a carreira (raros — secretário etc.)\n\n'
'### 3.4. Regime jurídico\n\n'
'**Estatutário** — regido por **lei** (estatuto), não por contrato. Direitos e deveres mutáveis pela lei.\n\n'
'### 3.5. Vínculo\n\n'
'Investidura por **posse + exercício** (não por assinatura de contrato).\n\n'
'## 4. Emprego Público\n\n'
'### 4.1. Conceito\n\n'
'Emprego público é o vínculo de natureza **contratual** entre o trabalhador e a entidade pública (geralmente EP, SEM, ou autarquia/fundação em casos pontuais), regido pela **CLT** (Consolidação das Leis do Trabalho).\n\n'
'### 4.2. Características\n\n'
'- Vínculo **contratual** (não estatutário)\n'
'- Regido pela **CLT**\n'
'- **Acessível por concurso público** (CF 37, II — STF RE 589.998)\n'
'- Sem estabilidade do art. 41 CF (mas exige motivação para dispensa em EP/SEM — STF RE 589.998)\n'
'- FGTS, aviso prévio, multa rescisória etc. da CLT\n\n'
'### 4.3. Onde se encontra\n\n'
'- **EP e SEM** (Petrobras, BB, Caixa, Correios)\n'
'- Eventualmente em **autarquias** que adotem regime celetista (raro)\n'
'- **Não** existe emprego público em Administração Direta (regra)\n\n'
'### 4.4. Distinções\n\n'
'| Aspecto | Cargo | Emprego |\n'
'|---|---|---|\n'
'| Vínculo | Estatutário | Contratual (CLT) |\n'
'| Lei | Estatuto (8.112) | CLT |\n'
'| Estabilidade | Art. 41 CF (efetivo) | Não (mas motivação para dispensa) |\n'
'| Local típico | Adm Direta + autarquias | EP + SEM |\n'
'| Investidura | Posse + exercício | Assinatura de contrato |\n\n'
'## 5. Função Pública\n\n'
'### 5.1. Conceito\n\n'
'Função pública é um **plexo de atribuições** exercido por uma pessoa física, **sem cargo correspondente** ou em **adição** ao cargo já ocupado.\n\n'
'### 5.2. Características\n\n'
'- **Não tem cargo** ou **cargo é apenas suporte**\n'
'- Pode ser **temporária** ou **permanente**\n'
'- Quase sempre é **gratificada** (recebe gratificação por desempenhá-la)\n\n'
'### 5.3. Modalidades\n\n'
'**a) Função de confiança:**\n'
'- **Exclusivamente para servidores efetivos** (CF 37, V)\n'
'- Função paralela ao cargo (chefia, direção, assessoramento)\n'
'- Recebe gratificação adicional\n'
'- Pode ser revogada a qualquer tempo\n\n'
'**b) Função temporária (servidor temporário):**\n'
'- Para necessidade temporária de excepcional interesse público (CF 37, IX)\n'
'- Regida pela **Lei 8.745/93** na União\n'
'- Vínculo **temporário** (não estatutário, não celetista — é regime especial)\n'
'- Exemplos: professores substitutos, contratados para combate à pandemia\n\n'
'**c) Função de chefia:**\n'
'- Comissionado (FG, FCC, FGR etc.)\n'
'- Símbolos por nível\n\n'
'### 5.4. Função temporária — exame mais detido\n\n'
'**CF art. 37, IX:** *"a lei estabelecerá os casos de contratação por tempo determinado para atender a necessidade temporária de excepcional interesse público"*.\n\n'
'**Lei 8.745/93 (regulamentação federal):**\n'
'- Prazos definidos\n'
'- Hipóteses taxativas (combate à seca, calamidade, professor substituto, atividades específicas)\n'
'- Vínculo não-estatutário e não-celetista — regime de **direito administrativo especial**\n'
'- Processo seletivo simplificado (não é concurso amplo)\n'
'- **STF (ADC 4):** competência da Justiça Federal Comum para causas de servidores temporários federais (não da Justiça do Trabalho)\n\n'
'## 6. Quadro comparativo geral\n\n'
'| Aspecto | Cargo Efetivo | Cargo em Comissão | Emprego Público | Função Temporária |\n'
'|---|---|---|---|---|\n'
'| Regime | Estatutário | Estatutário | CLT | Especial (Lei 8.745) |\n'
'| Concurso | Sim | Não | Sim | Seletivo simplificado |\n'
'| Estabilidade | Sim (após 3 anos) | Não | Não | Não |\n'
'| Local | Adm Direta + Indireta | Toda | EP + SEM | Toda |\n'
'| Investidura | Posse | Posse | Contrato | Contrato administrativo |\n'
'| Demissão | PAD com ampla defesa | Ad nutum | Motivação (RE 589.998) | Encerra prazo |\n\n'
'## 7. Discussão: agentes políticos\n\n'
'**Agentes políticos** são categoria à parte: ocupam funções de Estado pelo voto (Presidente, Governador, Prefeito, Vereador, Deputado, Senador) ou por investidura especial (Ministros, Procuradores-Gerais, Comandantes Militares).\n\n'
'**Diferença do cargo público comum:**\n'
'- Investidura sem concurso (eleição ou indicação)\n'
'- Regime constitucional próprio\n'
'- Não se aplicam diretamente as regras dos estatutários\n'
'- Responsabilidade política (impeachment) e jurídica (improbidade, crimes de responsabilidade)\n\n'
'## 8. Investidura\n\n'
'### 8.1. Cargo público\n'
'- Aprovação em concurso\n'
'- Nomeação\n'
'- Posse (até 30 dias da nomeação, prorrogável)\n'
'- Exercício (até 15 dias da posse)\n\n'
'### 8.2. Emprego público\n'
'- Aprovação em concurso ou processo seletivo público\n'
'- Assinatura do contrato de trabalho\n'
'- Início da prestação\n\n'
'### 8.3. Função temporária\n'
'- Processo seletivo simplificado\n'
'- Contrato administrativo de prazo determinado\n\n'
'## 9. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Empregado público tem estabilidade do art. 41" ❌ — só servidor estatutário\n'
'- "Empregado público pode ser dispensado sem motivação" ❌ — STF RE 589.998 exige motivação em EP/SEM\n'
'- "Função temporária dá direito a estabilidade" ❌ — encerra no prazo\n'
'- "Cargo em comissão exige concurso" ❌ — livre nomeação e exoneração\n'
'- "Função de confiança pode ser exercida por não-servidor" ❌ — exclusiva de efetivos (CF 37, V)\n'
'- "Servidor temporário é regido pela CLT" ❌ — regime especial\n\n'
'## 10. Conclusão\n\n'
'A distinção cargo/emprego/função é **basilar** no Direito Administrativo e altamente cobrada em concursos. Cargo é estatutário (regra na Adm Direta); emprego é celetista (regra em EP/SEM); função é exercício de atribuições sem cargo próprio (de confiança = exclusivo de efetivos; temporária = Lei 8.745). Dominar essas três categorias com clareza é essencial para acertar questões sobre regime jurídico, dispensa, estabilidade e responsabilização.\n',

  'Cargo público (Lei 8.112/90 art. 3º) = conjunto de atribuições atribuídas por lei a servidor; criado por lei, regime ESTATUTÁRIO. Tipos: efetivo (concurso, estável após 3 anos), em comissão (livre nomeação CF 37 II), vitalício. Emprego público = vínculo CONTRATUAL CLT, típico em EP/SEM, exige concurso (CF 37 II); sem estabilidade art. 41, mas exige motivação para dispensa em estatais (STF RE 589.998). Função pública = atribuições sem cargo próprio: função de confiança (CF 37 V — exclusiva de efetivos) e função/servidor temporário (CF 37 IX e Lei 8.745/93 — regime administrativo especial, não-CLT, processo seletivo simplificado).'
);

