'## 2. Fundamento\n\n'
'**Lei 8.112/90:**\n'
'- **Art. 121:** *"O servidor responde civil, penal e administrativamente pelo exercício irregular de suas atribuições."*\n'
'- **Art. 122:** responsabilidade civil\n'
'- **Art. 123:** responsabilidade penal\n'
'- **Art. 124:** responsabilidade administrativa\n'
'- **Art. 125:** **independência das instâncias**\n'
'- **Art. 126:** **vinculações** entre instâncias\n\n'
