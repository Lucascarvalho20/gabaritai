'### 7.1. Ato\n\n'
'**Manifestação de vontade** com efeito jurídico.\n\n'
'### 7.2. Fato\n\n'
'**Acontecimento** que produz efeito jurídico, sem manifestação de vontade. Exs.: morte do servidor (causa vacância), tempo (gera prescrição).\n\n'
