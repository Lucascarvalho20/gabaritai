'### 6.1. Atos normativos\n\n'
'Editam normas gerais e abstratas. Exs.: regulamentos, regimentos, decretos autônomos, instruções normativas.\n\n'
'### 6.2. Atos ordinatórios\n\n'
'Disciplinam o funcionamento interno da Administração. Exs.: instruções, circulares, avisos, ordens de serviço, portarias.\n\n'
'### 6.3. Atos negociais\n\n'
'Contêm **declaração de vontade da Administração coincidente com a pretensão do particular**. Exs.: licença, autorização, permissão, admissão, aprovação.\n\n'
'### 6.4. Atos enunciativos\n\n'
'**Atestam ou declaram** uma situação preexistente. Não criam direito, apenas constatam. Exs.: certidão, atestado, parecer.\n\n'
'### 6.5. Atos punitivos\n\n'
'Impõem **sanções** por ilícitos administrativos. Exs.: multa, advertência, suspensão, demissão, interdição.\n\n'
'## 7. Quanto à eficácia temporal\n\n'
'### 7.1. Atos válidos x inválidos\n\n'
'- **Válido:** em conformidade com a lei\n'
'- **Inválido:** com vício de validade (anulável)\n\n'
'### 7.2. Atos perfeitos x imperfeitos\n\n'
'- **Perfeito:** cumpriu todas as etapas de formação\n'
'- **Imperfeito:** etapa pendente (ex.: ato dependente de publicação)\n\n'
'### 7.3. Atos eficazes x ineficazes\n\n'
'- **Eficaz:** apto a produzir efeitos\n'
'- **Ineficaz:** com cláusula suspensiva, condição, prazo ou outro óbice\n\n'
'## 8. Quanto ao regime jurídico\n\n'
'### 8.1. Atos de império\n\n'
'Praticados no exercício da **autoridade soberana** do Estado, com prerrogativas. Exs.: desapropriação, requisição, atos de polícia.\n\n'
'### 8.2. Atos de gestão\n\n'
'Praticados em **regime semelhante ao privado**, sem prerrogativas especiais. Exs.: aluguel de imóvel pela Administração, compra de bens.\n\n'
'### 8.3. Atos de expediente\n\n'
'**Mero andamento interno** sem efeitos jurídicos imediatos. Exs.: ofício, memorando, encaminhamento de processos.\n\n'
'## 9. Espécies de atos negociais\n\n'
'### 9.1. Licença\n\n'
'**Ato vinculado** que faculta o exercício de **direito subjetivo** quando preenchidos os requisitos legais. Exs.: licença para construir (alvará de construção), licença para exercer profissão.\n\n'
'**Característica:** o particular tem **direito** (não mera expectativa) — basta provar os requisitos.\n\n'
'### 9.2. Autorização\n\n'
'**Ato discricionário, precário e revogável** que faculta atividade ou uso. Exs.: porte de arma, autorização para circo, autorização para uso de bem público.\n\n'
'**Característica:** **discricionária** (Administração pode negar mesmo se atendidos requisitos formais) e **precária** (pode ser revogada a qualquer tempo).\n\n'
'### 9.3. Permissão\n\n'
'**Ato discricionário e precário** que confere uso de bem público ou prestação de serviço público (esta última atualmente regulada por contrato — Lei 8.987/95).\n\n'
'**Distinção licença x autorização x permissão:**\n\n'
'| Aspecto | Licença | Autorização | Permissão |\n'
'|---|---|---|---|\n'
'| Natureza | Vinculada | Discricionária | Discricionária |\n'
'| Precariedade | Não | Sim | Sim |\n'
'| Atende | Direito subjetivo | Interesse particular | Interesse público |\n'
'| Exemplo | Licença para construir | Porte de arma | Uso de praça |\n\n'
'### 9.4. Admissão\n\n'
'**Ato vinculado** que insere o particular em estabelecimento ou serviço público. Exs.: admissão em escola pública, em hospital público.\n\n'
'### 9.5. Aprovação\n\n'
'**Ato pelo qual** se exerce **controle prévio (a priori)** ou **posterior (a posteriori)** sobre outro ato — confirmando sua validade.\n\n'
'### 9.6. Homologação\n\n'
'**Ato vinculado** que **confirma a legitimidade** de um ato anterior (controle a posteriori). Exs.: homologação de licitação, homologação de concurso.\n\n'
'## 10. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Licença é ato discricionário" ❌ — vinculado\n'
'- "Autorização confere direito subjetivo" ❌ — apenas faculta\n'
'- "Ato complexo e composto são sinônimos" ❌\n'
'- "Ato gerais têm destinatários determinados" ❌\n'
'- "Decreto é ato ordinatório" ❌ — normativo\n'
'- "Certidão impõe obrigação" ❌ — enunciativo\n'
'- "Permissão de uso de bem público gera direito adquirido" ❌\n\n'
'## 11. Conclusão\n\n'
'As classificações dos atos administrativos são o **mapa conceitual** do tema. Dominar as principais — vinculados/discricionários, simples/complexos/compostos, individuais/gerais e os tipos de atos negociais (licença/autorização/permissão) — resolve a maioria das questões objetivas em concursos policiais.\n',

  'Classificações dos atos administrativos: (1) Quanto à liberdade: vinculados (sem margem — controle judicial amplo) x discricionários (margem de escolha em motivo/objeto — controle pela razoabilidade). (2) Destinatário: individual (pessoa determinada) x geral (genérico). (3) Formação: SIMPLES (uma vontade), COMPLEXO (fusão de vontades de igual hierarquia — STF + Senado), COMPOSTO (principal + acessória — visto, aprovação). (4) Eficácia: internos x externos. (5) Conteúdo (Hely): normativos, ordinatórios, NEGOCIAIS, enunciativos, punitivos. Atos negociais: LICENÇA (vinculada — direito subjetivo); AUTORIZAÇÃO (discricionária, precária); PERMISSÃO (discricionária, precária, uso de bem ou serviço); admissão; aprovação; homologação. Validade/perfeição/eficácia.'
