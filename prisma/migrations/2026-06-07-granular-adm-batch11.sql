'## 1. Visão geral\n\n'
'A doutrina classifica os atos administrativos sob **diversos critérios**, cada um destacando aspectos específicos. Conhecer as classificações é essencial para identificar o regime aplicável e para resolver questões objetivas em concursos.\n\n'
'## 2. Quanto à liberdade de ação (vinculação)\n\n'
'### 2.1. Atos vinculados\n\n'
'A lei prevê integralmente os pressupostos e a consequência — não há margem para escolha. Diante do fato descrito, a Administração tem **dever** de praticar o ato.\n\n'
'**Exemplos:**\n'
'- Aposentadoria compulsória aos 75 anos\n'
'- Concessão de licença para tratamento de saúde\n'
'- Verificação de aptidão em exame admissional\n\n'
'**Controle judicial:** amplo, incidindo sobre todos os elementos.\n\n'
'### 2.2. Atos discricionários\n\n'
'A lei concede **margem de escolha** ao administrador quanto ao motivo e/ou objeto, dentro de balizas legais.\n\n'
'**Exemplos:**\n'
'- Permissão de uso de bem público\n'
'- Concessão de licença por interesse particular\n'
'- Autorização para porte de arma\n\n'
'**Controle judicial:** restrito ao mérito (legalidade, razoabilidade, proporcionalidade), preservando a discricionariedade legítima.\n\n'
'## 3. Quanto ao destinatário\n\n'
'### 3.1. Atos individuais\n\n'
'Endereçados a **pessoa ou pessoas determinadas**. Exs.: nomeação, demissão, multa específica.\n\n'
'### 3.2. Atos gerais\n\n'
'Endereçados a **destinatários indeterminados** ou genéricos. Exs.: decreto regulamentar, edital de concurso, instrução normativa.\n\n'
'## 4. Quanto à formação\n\n'
'### 4.1. Atos simples\n\n'
'Decorrem da **manifestação de vontade de um único órgão ou agente**. Exs.: portaria do ministro, despacho do gerente.\n\n'
'### 4.2. Atos complexos\n\n'
'Decorrem da **fusão de vontades de dois ou mais órgãos ou agentes**, formando um único ato. Exs.: nomeação de Ministro do STF (Presidente + Senado), aposentadoria com aprovação do TCU.\n\n'
'### 4.3. Atos compostos\n\n'
'**Manifestação principal de um órgão** + **manifestação acessória** (visto, homologação, aprovação) de outro. A vontade acessória apenas integra/confirma a principal.\n\n'
'**Distinção crucial:**\n'
'- **Complexo:** vontades de igual hierarquia fundem-se\n'
'- **Composto:** vontade principal + vontade acessória\n\n'
'## 5. Quanto à eficácia (alcance)\n\n'
'### 5.1. Atos internos\n\n'
'Produzem efeitos **dentro da Administração** — orientação a subordinados, organização interna. Exs.: circular, instrução interna.\n\n'
'### 5.2. Atos externos\n\n'
'Produzem efeitos **para fora da Administração** — atingem terceiros. Exs.: contratos, autorizações, decretos.\n\n'
