'| Culposo (§ 3º) | 1-3 anos detenção | Não (vara comum) | Nunca |\n\n'
'## 7. Conclusão\n\n'
'O homicídio é o tipo penal mais cobrado em concursos policiais — **quase certo em prova**. Para acertar, dominar: (a) espécies (simples, privilegiado, qualificado, culposo); (b) qualificadoras do § 2º (com atenção especial ao feminicídio); (c) Lei 13.142/15 (homicídio contra agente da segurança pública); (d) Pacote Anticrime (arma restrita); (e) súmula 18 STJ sobre perdão judicial. Estude com foco em **distinção entre motivo fútil e torpe** e **homicídio qualificado-privilegiado** (admitido pelo STF com qualificadora objetiva).\n',

