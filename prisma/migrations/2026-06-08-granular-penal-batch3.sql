'## 2. Calúnia (CP 138)\n\n'
'**CP art. 138:** *"Caluniar alguém, imputando-lhe falsamente fato definido como crime."*\n\n'
'**Pena:** detenção, 6 meses a 2 anos + multa.\n\n'
'### 2.1. Elementos\n\n'
'1. **Imputação** (atribuição) de fato a alguém\n'
'2. **Fato determinado** (não genérico) — exige descrição concreta\n'
'3. **Definido como crime** (não contravenção — esta seria difamação)\n'
'4. **Falsidade** — o agente sabe que o fato é falso\n\n'
