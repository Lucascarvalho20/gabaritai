'- **IV** — Deformidade permanente\n'
'- **V** — Aborto\n\n'
'**Distinção debilidade x perda:**\n'
'- **Debilidade:** redução funcional (perda de audição em 50%)\n'
'- **Perda:** ausência total ou inutilização (cegueira total)\n\n'
'### 2.4. Lesão Seguida de Morte (§ 3º) — Preterdoloso\n\n'
'**Pena:** reclusão, 4 a 12 anos.\n\n'
'**Conceito:** o agente quis **apenas lesionar**, mas o resultado morte ocorre **culposamente**.\n\n'
'**Estrutura:** dolo na lesão + culpa na morte = **crime preterdoloso**.\n\n'
'Distinção crucial:\n'
'- **Homicídio doloso:** quis matar OU assumiu o risco\n'
