'|---|---|---|---|\n'
'| Consumado | Consumada | Latrocínio consumado | 20-30 |\n'
'| Tentado | Consumada | Latrocínio consumado (S. 610 STF) | 20-30 |\n'
'| Consumado | Tentada | Latrocínio tentado | reduzido |\n'
'| Tentado | Tentada | Latrocínio tentado | reduzido |\n\n'
