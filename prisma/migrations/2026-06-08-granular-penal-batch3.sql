'## 2. Roubo Impróprio (§ 1º)\n\n'
'**CP art. 157, § 1º:** *"Na mesma pena incorre quem, logo depois de subtraída a coisa, emprega violência contra pessoa ou grave ameaça, a fim de assegurar a impunidade do crime ou a detenção da coisa para si ou para terceiro."*\n\n'
'### 2.1. Estrutura\n\n'
'1. **Subtração inicial sem violência** (similar a furto)\n'
'2. **Logo depois**, emprega violência/grave ameaça\n'
'3. **Finalidade:** assegurar a posse OU a impunidade\n\n'
'### 2.2. Exemplo\n\n'
'Ladrão furta carteira de bolso. Vítima percebe e tenta deter. Ladrão saca arma e ameaça. → ROUBO IMPRÓPRIO.\n\n'
'## 3. Causas de Aumento (§ 2º)\n\n'
'**Aumento de 1/3 até 1/2:**\n\n'
'- **II** — Concurso de duas ou mais pessoas\n'
'- **III** — Vítima em serviço de transporte de valores\n'
'- **IV** — Subtração de veículo automotor que venha a ser transportado para outro estado ou país\n'
'- **V** — Vítima é mantida em poder do agente (restrição de liberdade)\n'
'- **VI** — Subtração de substâncias explosivas ou armas de fogo de uso restrito\n'
'- **VII** — Praticado em via pública contra transeunte\n\n'
'### 3.1. Atenção: revogação do inciso I (arma)\n\n'
'**O inciso I (emprego de arma) FOI REVOGADO** pela Lei 13.654/18. Agora, o emprego de arma de fogo está no **§ 2º-A** (aumento de 2/3).\n\n'
'### 3.2. § 2º-A — Aumento de 2/3\n\n'
'- **I** — Se a violência ou ameaça é exercida com emprego de **arma de fogo**\n'
'- **II** — Se há destruição ou rompimento de obstáculo mediante explosivo\n\n'
'### 3.3. § 2º-B — Pena de reclusão de 7 a 15 anos + multa\n\n'
'Se a violência ou grave ameaça é exercida com emprego de **arma de fogo de uso restrito ou proibido** (Lei 13.964/19 — Pacote Anticrime).\n\n'
'### 3.4. Súmulas relevantes\n\n'
'**Súmula 174 STJ (cancelada):** "No crime de roubo, a intimidação feita com arma de brinquedo autoriza o aumento da pena." — **CANCELADA.** Hoje, arma de brinquedo NÃO autoriza aumento (entende-se que não é arma).\n\n'
'**Súmula 443 STJ:** *"O aumento na terceira fase de aplicação da pena no crime de roubo circunstanciado exige fundamentação concreta, não sendo suficiente para a sua exasperação a mera indicação do número de majorantes."*\n\n'
'## 4. Roubo Qualificado pelo Resultado (§§ 3º e 3º-A)\n\n'
'### 4.1. Roubo com lesão grave (§ 3º I)\n\n'
'**Pena:** reclusão, 7 a 18 anos + multa.\n\n'
'### 4.2. Latrocínio — Roubo com Morte (§ 3º II)\n\n'
'**Pena:** reclusão, **20 a 30 anos + multa**.\n\n'
'**É CRIME HEDIONDO** (Lei 8.072/90).\n\n'
'### 4.3. Características do latrocínio\n\n'
'- **Crime complexo** (roubo + homicídio)\n'
'- **Preterdoloso ou doloso** — pode haver dolo de matar OU culpa na morte (dolo no roubo + culpa no homicídio)\n'
'- **Competência:** **vara comum**, NÃO o tribunal do júri (Súmula 603 STF)\n\n'
'### 4.4. Súmula 610 STF\n\n'
'*"Há crime de latrocínio, quando o homicídio se consuma, ainda que não realize o agente a subtração de bens da vítima."*\n\n'
'**Significado:** se o agente mata mas não chega a subtrair, é latrocínio consumado (não tentado).\n\n'
'### 4.5. Súmula 603 STF\n\n'
'*"A competência para o processo e julgamento de latrocínio é do juiz singular e não do tribunal do júri."*\n\n'
'### 4.6. Tabela de combinações latrocínio\n\n'
