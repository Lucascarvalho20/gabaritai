SELECT upsert_material(
  'direito-administrativo',
  'Improbidade Administrativa',
  'Improbidade Administrativa: Lei 8.429/92 com a reforma da Lei 14.230/21',

E'# Improbidade Administrativa — Lei 8.429/92 (Reformada pela Lei 14.230/21)\n\n'
'## 1. Conceito\n\n'
'Improbidade administrativa é a prática, por **agente público** ou particular em concurso, de **conduta dolosa** que viole os princípios da Administração ou cause lesão ao erário ou enriquecimento ilícito, sujeitando o infrator a **sanções civis** (não criminais) previstas na **Lei 8.429/92**, com as profundas alterações da **Lei 14.230/21**.\n\n'
'É instrumento de **proteção da moralidade administrativa** (CF art. 37, § 4º), com natureza sancionatória de caráter cível-político-administrativo.\n\n'
'## 2. Fundamento constitucional\n\n'
'**CF art. 37, § 4º:** *"Os atos de improbidade administrativa importarão a suspensão dos direitos políticos, a perda da função pública, a indisponibilidade dos bens e o ressarcimento ao erário, na forma e gradação previstas em lei, sem prejuízo da ação penal cabível."*\n\n'
'**Natureza:** **cível-sancionatória**. Não é nem criminal nem puramente civil. STF tem entendimento próprio sobre as garantias aplicáveis.\n\n'
'## 3. A Reforma da Lei 14.230/21 — pontos críticos\n\n'
'A Lei 14.230, de 25/10/2021, alterou substancialmente a Lei 8.429/92, gerando intensa polêmica. Principais mudanças:\n\n'
'### 3.1. Fim da modalidade culposa\n\n'
'**Antes:** improbidade por lesão ao erário (art. 10) podia ser dolosa ou **culposa**.\n'
'**Após Lei 14.230/21:** **somente atos dolosos** caracterizam improbidade (novo art. 1º, § 1º). O dolo deve ser **específico** — vontade dirigida ao resultado ímprobo.\n\n'
'**STF (ARE 843.989 — repercussão geral, 2022):** a vedação da modalidade culposa **NÃO retroage** para favorecer réus em processos com decisão definitiva ou trânsito em julgado. Mas se aplica imediatamente aos processos em andamento e às condutas posteriores.\n\n'
'### 3.2. Violação a princípios — alteração\n\n'
'**Antes (art. 11):** rol exemplificativo, qualquer violação aos princípios da Administração\n'
'**Após Lei 14.230/21:** rol **taxativo** (numerus clausus) — só os incisos do art. 11. **Exigência de dolo específico** + **finalidade ilícita ou de obter benefício pessoal**.\n\n'
'### 3.3. Particulares como agentes ímprobos\n\n'
'**Antes:** particular podia ser réu sozinho se concorria para improbidade.\n'
'**Após Lei 14.230/21:** **necessidade de concurso com agente público** (art. 3º). Não há improbidade exclusivamente do particular.\n\n'
'### 3.4. Prescrição\n\n'
