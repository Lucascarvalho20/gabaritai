'3. **Agentes "nessa qualidade"** — exercício da função\n'
'4. **Danos a terceiros**\n'
'5. **Direito de regresso** contra o agente (com dolo ou culpa)\n\n'
'## 4. Características da responsabilidade objetiva\n\n'
'### 4.1. Elementos\n\n'
'Para configurar a responsabilidade, basta:\n'
'1. **Conduta estatal** (ação ou omissão)\n'
'2. **Dano** (material, moral, estético)\n'
'3. **Nexo de causalidade**\n\n'
'**Não se exige:** dolo, culpa, identificação do agente.\n\n'
'### 4.2. Dispensa da culpa\n\n'
'O lesado **não precisa provar culpa** da Administração — apenas o nexo entre o ato e o dano.\n\n'
