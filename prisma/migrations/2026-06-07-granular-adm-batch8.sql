-- 2/8 — Sindicância Administrativa
-- =====================================================================
SELECT upsert_material(
  'direito-administrativo',
  'Sindicância Administrativa',
  'Sindicância Administrativa: procedimento sumário de apuração disciplinar',

E'# Sindicância Administrativa\n\n'
'## 1. Conceito\n\n'
'Sindicância é o **procedimento administrativo de apuração preliminar** de irregularidade ou infração funcional, mais célere e simplificado que o PAD ordinário, podendo culminar em arquivamento, aplicação de penalidade leve ou instauração de PAD para apurar fatos mais graves.\n\n'
'É instrumento típico da Administração para esclarecimento prévio de fatos suspeitos, antes de mobilizar os recursos processuais maiores do PAD ordinário.\n\n'
'## 2. Fundamento normativo\n\n'
'- **Lei 8.112/90 art. 143:** *"A autoridade que tiver ciência de irregularidade no serviço público é obrigada a promover a sua apuração imediata, mediante sindicância ou processo administrativo disciplinar, assegurada ao acusado ampla defesa"*\n'
'- **Lei 8.112/90 arts. 145-146:** disciplina específica da sindicância\n\n'
'## 3. Espécies de sindicância\n\n'
'A doutrina e a prática administrativa diferenciam:\n\n'
'### 3.1. Sindicância investigatória (ou preparatória, ou inquisitorial)\n\n'
'- **Caráter:** preliminar, exploratório\n'
'- **Objetivo:** verificar se há indícios de irregularidade que justifiquem a instauração de PAD\n'
'- **Contraditório:** **dispensado** (ainda não há acusado)\n'
'- **Resultado:** arquivamento OU instauração de PAD\n'
'- **Não pode** aplicar penalidade — porque não houve contraditório\n\n'
'### 3.2. Sindicância contraditória (ou acusatória)\n\n'
'- **Caráter:** processual com contraditório\n'
'- **Objetivo:** apurar e eventualmente punir\n'
'- **Contraditório:** **obrigatório** (Súmula Vinculante 5; Lei 8.112/90)\n'
'- **Pode** aplicar **advertência** ou **suspensão até 30 dias**\n'
'- Se for o caso de penalidade mais grave (demissão, cassação, destituição, suspensão acima de 30 dias) → instaura-se PAD\n\n'
'### 3.3. Sindicância patrimonial\n\n'
'- Modalidade prevista em normas internas (ex.: CGU)\n'
'- Investiga **evolução patrimonial incompatível** do servidor\n'
'- Pode levar a PAD por improbidade ou enriquecimento ilícito\n\n'
'## 4. Prazo e prorrogação\n\n'
'**Lei 8.112/90 art. 145, parágrafo único:**\n\n'
'- **Prazo de conclusão:** 30 dias\n'
'- **Prorrogação:** mais 30 dias, justificadamente\n\n'
'Vencido o prazo, a sindicância não é nula automaticamente, mas a autoridade fica em mora.\n\n'
'## 5. Comissão sindicante\n\n'
'### 5.1. Composição\n\n'
'A Lei 8.112/90 não exige número específico. A prática:\n'
'- **1 sindicante:** comum nas sindicâncias investigatórias mais simples\n'
'- **3 servidores:** quando se prevê possibilidade de penalidade leve (com contraditório)\n\n'
'### 5.2. Requisitos\n\n'
'- Servidores estáveis (preferencialmente)\n'
'- Imparcialidade — sem vínculo com o investigado\n'
'- Designados por portaria da autoridade competente\n\n'
'## 6. Procedimento\n\n'
'### 6.1. Instauração\n\n'
'- **Portaria** da autoridade competente, com descrição sumária dos fatos\n'
'- Publicação no Diário Oficial (sindicância contraditória)\n\n'
'### 6.2. Instrução\n\n'
'- Oitiva de testemunhas\n'
'- Coleta de documentos\n'
'- Perícias se necessárias\n'
'- Diligências em órgãos externos\n\n'
'### 6.3. Defesa (apenas na contraditória)\n\n'
'- Notificação do indiciado\n'
'- Prazo para defesa (geralmente 10 dias)\n'
'- Defesa técnica facultativa (SV 5)\n\n'
'### 6.4. Relatório\n\n'
'- Conclusões da comissão\n'
'- Sugestão de penalidade ou arquivamento\n\n'
'### 6.5. Decisão\n\n'
'- Autoridade competente\n'
'- Pode aplicar penalidade (até suspensão de 30 dias) ou determinar instauração de PAD\n\n'
'## 7. Penalidades cabíveis\n\n'
'**Apenas na sindicância contraditória:**\n\n'
'- **Advertência** (art. 129 Lei 8.112/90)\n'
'- **Suspensão até 30 dias** (art. 130, § 1º)\n\n'
'Para penalidades mais severas (demissão, cassação, destituição, suspensão superior a 30 dias) → **instaura-se PAD ordinário**.\n\n'
'## 8. Diferença entre sindicância e PAD\n\n'
'| Aspecto | Sindicância | PAD Ordinário |\n'
'|---|---|---|\n'
'| Caráter | Sumário / preliminar | Pleno / completo |\n'
'| Prazo | 30 + 30 dias | 60 + 60 dias |\n'
'| Comissão | 1 ou 3 servidores | 3 servidores estáveis |\n'
'| Contraditório | Só na acusatória | Obrigatório |\n'
'| Penalidade máxima | Suspensão 30 dias | Demissão, cassação, destituição |\n'
'| Sequência | Pode preceder PAD | Pode ser instaurado direto |\n\n'
'## 9. Relação com o PAD\n\n'
'A sindicância **não é obrigatória** antes do PAD. A autoridade pode:\n\n'
'1. Instaurar diretamente o PAD (quando há indícios suficientes)\n'
'2. Instaurar sindicância investigatória primeiro\n'
'3. Após sindicância contraditória, instaurar PAD se a apuração indicar penalidade mais grave\n\n'
'Caso a sindicância seja contraditória e tenha aplicado advertência ou suspensão até 30 dias, **não cabe PAD posterior pelos mesmos fatos** (bis in idem).\n\n'
'## 10. Características técnicas\n\n'
'- **Vinculação a fatos concretos:** a sindicância não pode ser usada como "pesca" genérica\n'
'- **Sigilo:** pode tramitar em sigilo durante a instrução, conforme o caso\n'
'- **Acesso aos autos:** assegurado ao indiciado na sindicância contraditória\n\n'
'## 11. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Sindicância sempre exige contraditório" ❌ — só a contraditória/acusatória\n'
'- "Sindicância pode aplicar demissão" ❌ — só advertência ou suspensão até 30 dias\n'
'- "PAD exige sindicância prévia" ❌ — pode-se instaurar PAD diretamente\n'
'- "Sindicância investigatória aplica penalidade" ❌\n'
'- "Sindicância tem prazo de 60 dias" ❌ — é 30 + 30\n'
'- "Comissão de sindicância deve ter 3 membros" — depende do caso (pode ter 1 na investigatória)\n\n'
'## 12. Conclusão\n\n'
'A sindicância é o **instrumento ágil de apuração disciplinar**, com dupla função: investigatória (preliminar, sem contraditório) e contraditória (com contraditório, capaz de aplicar penalidades leves). Conhecer a distinção entre as duas modalidades, os prazos, a relação com o PAD e os limites das penalidades é essencial para concursos policiais e administrativos.\n',

  'Sindicância (Lei 8.112/90 arts. 145-146) é procedimento sumário de apuração disciplinar. Espécies: investigatória (sem contraditório, só arquivamento ou PAD) e contraditória (com contraditório, pode aplicar advertência ou suspensão até 30 dias). Prazo 30+30 dias. PAD não exige sindicância prévia. Comissão de 1 ou 3 servidores (estáveis preferencialmente). Para penalidades mais graves (demissão, suspensão > 30 dias), instaura-se PAD ordinário. Súmula Vinculante 5 STF: dispensa defesa técnica. Não cabe bis in idem.'
);

