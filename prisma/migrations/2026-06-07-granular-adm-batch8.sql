SELECT upsert_material(
  'direito-administrativo',
  'Processo Administrativo Disciplinar',
  'Processo Administrativo Disciplinar (PAD): fases, ritos e garantias (Lei 8.112/90)',

E'# Processo Administrativo Disciplinar (PAD)\n\n'
'## 1. Conceito\n\n'
'O Processo Administrativo Disciplinar (PAD) é o **instrumento formal e contraditório** pelo qual a Administração Pública apura a responsabilidade do servidor público por infração funcional, garantindo ampla defesa e contraditório, e podendo culminar em sanção disciplinar (advertência, suspensão, demissão, cassação de aposentadoria, destituição de cargo em comissão).\n\n'
'É a **manifestação concreta do poder disciplinar** sobre os agentes públicos, sob as garantias do devido processo legal substantivo (CF art. 5º, LIV e LV).\n\n'
'## 2. Fundamento normativo\n\n'
'### 2.1. Constituição Federal\n\n'
'- **Art. 5º, LIV:** ninguém será privado de bens sem o devido processo legal\n'
'- **Art. 5º, LV:** *"aos litigantes, em processo judicial ou administrativo, e aos acusados em geral são assegurados o contraditório e ampla defesa, com os meios e recursos a ela inerentes"*\n'
'- **Art. 37, caput:** moralidade administrativa\n'
'- **Art. 41, § 1º, II:** servidor estável só perde cargo mediante PAD\n\n'
'### 2.2. Lei 8.112/90 (Estatuto dos Servidores Federais)\n\n'
'- **Arts. 116-117:** deveres e proibições\n'
'- **Arts. 121-126:** responsabilidades civil, penal e administrativa\n'
'- **Arts. 127-142:** penalidades\n'
'- **Arts. 143-182:** processo disciplinar\n\n'
'### 2.3. Lei 9.784/99 (Processo Administrativo Federal — supletiva)\n\n'
'Aplica-se subsidiariamente, garantindo princípios gerais.\n\n'
'## 3. Modalidades de apuração disciplinar\n\n'
'### 3.1. Sindicância\n\n'
'**Procedimento sumário** para apuração preliminar de irregularidades, com prazo de 30 dias prorrogáveis por mais 30 (Lei 8.112/90 art. 145). Pode culminar em:\n\n'
'- **Arquivamento** (não há irregularidade)\n'
'- **Aplicação de penalidade leve** (advertência ou suspensão até 30 dias) — desde que assegurado o contraditório (sindicância contraditória)\n'
'- **Instauração de PAD** (para infrações graves)\n\n'
'### 3.2. PAD ordinário\n\n'
'Procedimento completo, para apuração de infrações graves que possam resultar em **demissão, cassação de aposentadoria ou destituição de cargo em comissão**.\n\n'
'### 3.3. Rito sumário (Lei 8.112/90 arts. 133-134)\n\n'
'Aplicável apenas em hipóteses específicas:\n\n'
'- **Acumulação ilegal de cargos** (art. 133)\n'
'- **Abandono de cargo** (art. 138 — ausência por mais de 30 dias)\n'
'- **Inassiduidade habitual** (art. 139 — faltas injustificadas que excedam 60 dias intercalados ao longo de 12 meses)\n\n'
'Prazo: 30 dias prorrogáveis por mais 15.\n\n'
'## 4. Fases do PAD\n\n'
'### 4.1. Instauração\n\n'
'- Por **portaria** da autoridade competente\n'
'- Descrição sumária dos fatos\n'
'- Designação de **comissão processante** (3 servidores estáveis, sendo presidente de cargo igual ou superior ao do acusado, mais 2 membros). Lei 8.112/90 art. 149\n'
'- Publicação no Diário Oficial\n\n'
'### 4.2. Inquérito Administrativo\n\n'
'É a **fase principal**, dividida em três subfases:\n\n'
'**a) Instrução** (arts. 153-159):\n'
'- Coleta de provas: depoimentos, perícias, juntada de documentos\n'
'- Acareações se necessário\n'
'- Direito do acusado de acompanhar pessoalmente ou por advogado\n'
'- Notificação do acusado para todos os atos\n\n'
'**b) Defesa** (arts. 161-164):\n'
'- **Indiciação** formal do servidor (notificação com prazo para defesa)\n'
'- Prazo de **10 dias** para defesa escrita (20 dias se mais de 1 indiciado, dobrável)\n'
'- Defesa por advogado é facultativa, **mas a Súmula Vinculante 5 STF** afirma: *"A falta de defesa técnica por advogado no processo administrativo disciplinar não ofende a Constituição"*\n\n'
'**c) Relatório** (art. 165):\n'
'- Relatório conclusivo da comissão\n'
'- Apreciação da prova\n'
'- Indicação dos dispositivos legais infringidos\n'
'- Proposta de penalidade ou arquivamento\n\n'
'### 4.3. Julgamento\n\n'
'- Pela **autoridade competente** (não pela comissão)\n'
'- Prazo de **20 dias** (art. 167)\n'
'- A autoridade pode:\n'
'  - **Concordar** com o relatório\n'
'  - **Discordar fundamentadamente** (se a prova autorizar conclusão diversa)\n'
'  - **Determinar diligências complementares**\n'
'- Decisão **motivada** (Lei 9.784/99 art. 50)\n\n'
'## 5. Penalidades (Lei 8.112/90 art. 127)\n\n'
'### 5.1. Advertência\n\n'
'Sanção leve, por escrito. Aplicada por inobservância de dever funcional sem maior gravidade. Prescreve em **180 dias** (art. 142, III).\n\n'
'### 5.2. Suspensão\n\n'
'Até 90 dias. Em caso de reincidência das faltas advertidas ou outras transgressões. Prescreve em **2 anos**.\n\n'
'### 5.3. Demissão\n\n'
'Hipóteses do art. 132: crime contra a Administração, abandono, improbidade, lesão aos cofres públicos, corrupção, insubordinação grave, ofensa física a outro servidor, conduta escandalosa etc.\n\n'
'### 5.4. Cassação de aposentadoria ou disponibilidade\n\n'
'Para os inativos que tenham praticado, na ativa, falta punível com demissão (art. 134).\n\n'
'### 5.5. Destituição de cargo em comissão / função comissionada\n\n'
'Para ocupante de CC ou função comissionada que não seja servidor efetivo (art. 135).\n\n'
'## 6. Prescrição (art. 142)\n\n'
'### 6.1. Prazos\n\n'
'- **5 anos:** infrações puníveis com demissão, cassação de aposentadoria, destituição\n'
'- **2 anos:** infrações puníveis com suspensão\n'
'- **180 dias:** infrações puníveis com advertência\n\n'
'### 6.2. Termo inicial\n\n'
'A partir do **conhecimento da infração pela autoridade**.\n\n'
'### 6.3. Interrupção\n\n'
'**Abertura de sindicância ou instauração de PAD interrompe a prescrição**, que retoma a fluência integral após o prazo legal de conclusão (art. 142, § 3º).\n\n'
'### 6.4. Crime\n\n'
'Quando a infração disciplinar é também crime, aplica-se a **prescrição penal** (art. 142, § 2º), que costuma ser mais longa.\n\n'
'## 7. Garantias do servidor (princípios)\n\n'
'- **Devido processo legal**\n'
'- **Contraditório e ampla defesa** (CF 5º LV)\n'
'- **Presunção de inocência** até decisão final\n'
'- **Direito ao silêncio**\n'
'- **Acesso a todos os autos**\n'
'- **Direito de produzir provas**\n'
'- **Imparcialidade da comissão**\n'
'- **Motivação da decisão**\n'
'- **Vedação à reformatio in pejus** em recurso próprio do acusado\n\n'
'## 8. Recursos\n\n'
'- **Pedido de reconsideração:** prazo de 30 dias à autoridade que aplicou a sanção\n'
'- **Recurso hierárquico:** prazo de 10 dias à autoridade superior, sucessivamente (Lei 9.784/99 art. 56)\n'
'- **Revisão:** a qualquer tempo, se houver fatos novos ou circunstâncias suscetíveis de justificar a inocência (art. 174 Lei 8.112/90). Cabe apenas em favor do servidor — **nunca para agravar** a pena (art. 174, parágrafo único)\n\n'
'## 9. Nulidades\n\n'
'Causas frequentes de nulidade:\n'
'- Comissão composta por servidores não-estáveis ou em cargo inferior\n'
'- Negativa de acesso aos autos\n'
'- Cerceamento de defesa\n'
'- Ausência de notificação para atos relevantes\n'
'- Comissão tendenciosa (relação com o acusado)\n'
'- Ausência de motivação na decisão\n'
'- Vícios na indiciação (capitulação genérica)\n\n'
'## 10. Verdade real x verdade formal\n\n'
'O PAD segue o princípio da **verdade real** (busca-se a realidade dos fatos, não a verdade formal das alegações), diferentemente do processo civil. A comissão deve **diligenciar de ofício**.\n\n'
'## 11. Independência das instâncias\n\n'
'**Lei 8.112/90 arts. 121-126:** a responsabilidade administrativa é independente da civil e da penal, podendo haver:\n\n'
'- Absolvição penal por **insuficiência de provas** — não afasta a sanção administrativa\n'
'- Absolvição penal por **inexistência do fato ou autoria** — **afasta** a sanção administrativa (vínculo)\n'
'- Condenação penal não obriga sanção administrativa, mas seus efeitos podem ser aproveitados\n\n'
'## 12. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Servidor estável pode ser demitido sem PAD" ❌ — exige-se PAD (CF 41 § 1º)\n'
'- "Defesa técnica por advogado é obrigatória no PAD" ❌ — SV 5 STF\n'
'- "Comissão pode aplicar penalidade" ❌ — só propõe; quem aplica é a autoridade\n'
'- "Prescrição da pena de demissão é 2 anos" ❌ — é 5 anos\n'
'- "Revisão pode agravar a pena" ❌\n'
'- "Sindicância sempre precede PAD" ❌ — pode-se instaurar PAD diretamente\n\n'
'## 13. Conclusão\n\n'
'O PAD é o **principal instrumento de controle disciplinar** sobre os agentes públicos. Para concursos policiais (PF, PRF, PC), domínio das fases (instauração → inquérito → julgamento), das penalidades (art. 127), da prescrição (art. 142) e das nulidades é fundamental. A Súmula Vinculante 5 STF (dispensa de defesa técnica) é cobrada com frequência.\n',

  'PAD é instrumento formal e contraditório para apurar infração funcional (Lei 8.112/90 arts. 143-182). Fases: instauração (portaria, comissão de 3 servidores estáveis), inquérito (instrução + defesa + relatório — 10 dias defesa), julgamento (autoridade, 20 dias). Penalidades art. 127: advertência (prescrição 180 dias), suspensão até 90d (2 anos), demissão, cassação aposentadoria, destituição CC (5 anos). Garantias: contraditório, ampla defesa (CF 5º LV; SV 5 STF dispensa defesa técnica), verdade real. Independência das instâncias civil/penal/adm. Revisão a qualquer tempo, só pró-réu (art. 174).'
);

