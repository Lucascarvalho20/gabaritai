'### 2.1. Teoria da irresponsabilidade\n'
'**"The king can do no wrong"** — fase em que o Estado não respondia por danos (Estado absolutista).\n\n'
'### 2.2. Teoria da responsabilidade civilista (subjetiva)\n'
'Exigia comprovação de **dolo ou culpa** do agente. Inspirada no Código Civil francês de 1804.\n\n'
'### 2.3. Teoria da culpa administrativa (faute du service)\n'
'Quando o serviço **não funcionou, funcionou mal ou tardiamente**, presumindo-se a culpa anônima da Administração. Não exige identificar o agente faltoso.\n\n'
'### 2.4. Teoria do risco administrativo (CF 88)\n'
'**Responsabilidade objetiva** — basta o nexo entre conduta estatal e dano. Não exige culpa. Admite excludentes.\n\n'
'### 2.5. Teoria do risco integral\n'
'Responsabilidade absoluta — sem excludentes (caso fortuito ou força maior não rompem o nexo). Aplica-se em hipóteses excepcionais.\n\n'
'## 3. Fundamento constitucional\n\n'
'**CF art. 37, § 6º:** *"As pessoas jurídicas de direito público e as de direito privado prestadoras de serviços públicos responderão pelos danos que seus agentes, nessa qualidade, causarem a terceiros, assegurado o direito de regresso contra o responsável nos casos de dolo ou culpa."*\n\n'
