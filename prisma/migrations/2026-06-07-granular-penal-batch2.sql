-- 1/8 — Concurso de Pessoas
-- =====================================================================
SELECT upsert_material(
  'direito-penal',
  'Concurso de Pessoas',
  'Concurso de Pessoas: autoria, coautoria, participação (CP 29-31)',

E'# Concurso de Pessoas\n\n'
'## 1. Conceito\n\n'
'**Concurso de pessoas** é a **convergência de duas ou mais pessoas** para a prática de uma infração penal. É o instituto que disciplina a responsabilidade penal quando o crime é cometido por mais de um agente.\n\n'
'O CP brasileiro adota, em regra, a **teoria monista (unitária)**: todos os concorrentes respondem por um único crime. **CP art. 29:** *"Quem, de qualquer modo, concorre para o crime incide nas penas a este cominadas, na medida de sua culpabilidade."*\n\n'
'## 2. Teorias\n\n'
'### 2.1. Teoria Monista (Unitária)\n\n'
'**Adotada como REGRA pelo CP** — todos os concorrentes respondem **pelo mesmo crime**. O fato é único, a participação de cada um é apenas modo de sua execução.\n\n'
'### 2.2. Teoria Pluralista\n\n'
'Cada concorrente comete crime distinto. **Exceções no CP:**\n'
'- **Aborto provocado por terceiro com consentimento da gestante:** terceiro responde por CP 126; gestante por CP 124\n'
'- **Bigamia (CP 235):** o cônjuge bígamo e o terceiro que com ele se casa respondem por crimes distintos\n'
'- **Corrupção ativa (CP 333) x passiva (CP 317):** crimes distintos para quem oferece e quem recebe\n'
'- **Falso testemunho mediante suborno (CP 343):** quem testemunha falsamente (342) e quem suborna (343)\n\n'
'### 2.3. Teoria Dualista\n\n'
'Distingue **autores** (crime principal) de **partícipes** (crime acessório). Não é adotada pelo CP em geral.\n\n'
'## 3. Requisitos do concurso de pessoas\n\n'
'### 3.1. Pluralidade de agentes e condutas\n'
'No mínimo duas pessoas com condutas distintas (autor + autor; autor + partícipe).\n\n'
'### 3.2. Relevância causal da conduta\n'
'A conduta de cada concorrente deve ter contribuído causalmente para o crime (CP 13).\n\n'
'### 3.3. Vínculo subjetivo (liame psicológico)\n'
'**Adesão consciente** à conduta criminosa alheia. Não é necessário acordo prévio — basta consciência de contribuir para o fato comum.\n\n'
'**Sem vínculo subjetivo: autoria colateral** (cada qual responde pelo que fez isoladamente).\n\n'
'### 3.4. Identidade de infração\n\n'
'Em regra, todos respondem pela mesma infração (teoria monista).\n\n'
'## 4. Autoria\n\n'
'### 4.1. Teorias da autoria\n\n'
'**a) Teoria objetivo-formal (tradicional):** autor é quem **realiza a conduta típica** (executa o verbo); partícipe é quem contribui sem realizar diretamente.\n\n'
'**b) Teoria objetivo-material:** autor é quem dá contribuição **mais importante** ao crime.\n\n'
'**c) Teoria do domínio do fato (Roxin):** autor é quem **detém o controle final** do crime, podendo decidir sua execução ou interrupção. Adotada para crimes contra a ordem econômica (Operação Lava Jato).\n\n'
'**d) Teoria subjetiva (causal):** distingue autor (animus auctoris) e partícipe (animus socii) pelo elemento volitivo. Pouco utilizada.\n\n'
'### 4.2. Espécies de autoria\n\n'
'**a) Autoria imediata (direta):** o autor pratica diretamente a conduta típica.\n\n'
'**b) Autoria mediata:** o autor utiliza terceiro como instrumento, sem que este seja culpável. Ex: usar criança ou doente mental para furtar.\n\n'
'**c) Coautoria:** duas ou mais pessoas executam **conjuntamente** a conduta. Cada uma realiza parte do verbo típico.\n\n'
'**d) Autoria colateral:** dois ou mais agentes atuam **sem vínculo subjetivo**, cada um buscando seu próprio resultado. Não há concurso de pessoas — cada um responde pelo que efetivamente fez.\n\n'
'**e) Autoria incerta:** quando, em autoria colateral, não se sabe qual conduta produziu o resultado. Solução: ambos respondem por tentativa.\n\n'
'## 5. Participação\n\n'
'### 5.1. Conceito\n\n'
'**Partícipe** é quem **contribui causalmente** para o crime **sem realizar diretamente** o verbo típico.\n\n'
'### 5.2. Espécies\n\n'
'**a) Participação moral:**\n'
'- **Induzimento:** plantar a ideia criminosa em mente que não a tinha\n'
'- **Instigação:** reforçar ideia criminosa já existente\n\n'
'**b) Participação material:**\n'
'- **Cumplicidade:** auxílio material à execução (fornecer arma, emprestar carro)\n\n'
'### 5.3. Participação de menor importância (CP 29 § 1º)\n\n'
'*"Se a participação for de menor importância, a pena pode ser diminuída de um sexto a um terço."*\n\n'
'Aplica-se quando o partícipe teve contribuição **pequena**, **secundária**.\n\n'
'### 5.4. Cooperação dolosamente distinta (CP 29 § 2º)\n\n'
'*"Se algum dos concorrentes quis participar de crime menos grave, ser-lhe-á aplicada a pena deste; essa pena será aumentada até metade, na hipótese de ter sido previsível o resultado mais grave."*\n\n'
'**Hipótese clássica:** A combina com B um furto. B, durante a execução, mata o morador. A não previa o homicídio.\n\n'
'**Solução:** A responde **apenas pelo furto** (que foi o que quis), com pena eventualmente aumentada até a metade se o homicídio era previsível.\n\n'
'## 6. Comunicabilidade das circunstâncias (CP 30)\n\n'
'### 6.1. Regra\n\n'
'**CP art. 30:** *"Não se comunicam as circunstâncias e as condições de caráter pessoal, salvo quando elementares do crime."*\n\n'
'### 6.2. Tipologia\n\n'
'**a) Circunstâncias objetivas (reais):** vinculadas ao fato (meio empregado, lugar, tempo). **Comunicam-se** a todos os concorrentes que delas tiveram conhecimento.\n\n'
'**b) Circunstâncias subjetivas (pessoais):** vinculadas à pessoa do agente (motivo, antecedentes, parentesco). **NÃO se comunicam**, salvo se forem **elementares do tipo**.\n\n'
'### 6.3. Elementares\n\n'
'**Elementares** são dados que **integram a definição do tipo** (sem eles, o crime muda ou inexiste). Ex: "funcionário público" no peculato (CP 312).\n\n'
'**Comunicam-se mesmo se subjetivas**, desde que o coautor/partícipe **conhecesse** a condição. Ex: particular que ajuda funcionário público em peculato responde por peculato (a condição de "servidor" é elementar e comunica-se).\n\n'
'## 7. Casos de impunibilidade do partícipe (CP 31)\n\n'
'**CP art. 31:** *"O ajuste, a determinação ou instigação e o auxílio, salvo disposição expressa em contrário, não são puníveis, se o crime não chega, pelo menos, a ser tentado."*\n\n'
'**Significado:** a participação só é punível se houve **início de execução** do crime principal. Se o crime não foi nem tentado, o partícipe não responde.\n\n'
'**Exceção:** quando o ajuste/instigação é tipificado autonomamente (ex: associação criminosa — CP 288).\n\n'
'## 8. Crime multitudinário\n\n'
'Crimes cometidos por **multidão** sob a influência de paixões coletivas. A doutrina e jurisprudência atribuem **atenuação** com base no CP 65 III "e" (sob influência de violenta emoção).\n\n'
'## 9. Concurso em crime culposo\n\n'
'**Doutrina majoritária:** admite-se **coautoria** em crime culposo, mas **não participação** (porque na culpa não há vontade dirigida ao resultado).\n\n'
'## 10. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Teoria adotada é a pluralista" ❌ — monista (CP 29)\n'
'- "Sem vínculo subjetivo há concurso de pessoas" ❌ — é autoria colateral\n'
'- "Elementares pessoais não se comunicam" ❌ — comunicam-se (CP 30)\n'
'- "Partícipe responde mesmo se o crime não foi tentado" ❌ — CP 31\n'
'- "Cabe participação em crime culposo" ❌ — só coautoria\n'
'- "Domínio do fato é a regra do CP" ❌ — adotada apenas pela jurisprudência em casos específicos\n'
'- "Cooperação dolosamente distinta aplica-se ao crime mais grave" ❌ — aplica a pena do crime MENOS grave (com aumento se previsível)\n\n'
'## 11. Conclusão\n\n'
'O concurso de pessoas é matéria **certa em qualquer prova de Penal**. Para concursos, dominar: (a) teoria monista (CP 29) com exceções pluralistas; (b) requisitos (vínculo subjetivo é central); (c) autoria, coautoria, autoria colateral, autoria mediata; (d) participação de menor importância (§ 1º) e cooperação dolosamente distinta (§ 2º); (e) regra do CP 30 (elementares comunicam-se; circunstâncias subjetivas não, salvo elementares); (f) CP 31 (participação só se há início de execução).\n',

  'Concurso de pessoas (CP 29-31): TEORIA MONISTA (regra — todos respondem pelo mesmo crime), com exceções PLURALISTAS (aborto consensual, bigamia, corrupção ativa x passiva, falso testemunho x suborno). Requisitos: pluralidade de agentes + relevância causal + VÍNCULO SUBJETIVO + identidade de infração. Sem vínculo subjetivo = AUTORIA COLATERAL (cada um responde pelo que fez). Teorias da autoria: objetivo-formal (autor = quem executa), domínio do fato (Roxin — controle final, aplicado em Lava Jato). Espécies: imediata, mediata (terceiro como instrumento), coautoria, colateral, incerta. Participação: moral (induzimento/instigação) e material (cumplicidade). PARTICIPAÇÃO DE MENOR IMPORTÂNCIA (§ 1º) reduz 1/6 a 1/3. COOPERAÇÃO DOLOSAMENTE DISTINTA (§ 2º): partícipe responde pelo crime MENOS grave; aumento até 1/2 se o mais grave era previsível. CP 30: circunstâncias objetivas comunicam-se (se conhecidas); subjetivas NÃO, salvo se ELEMENTARES (ex: funcionário público em peculato comunica ao particular). CP 31: ajuste/instigação não é punível se o crime não foi pelo menos tentado.'
);

