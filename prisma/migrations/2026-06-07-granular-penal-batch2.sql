SELECT upsert_material(
  'direito-penal',
  'Tentativa e Consumação',
  'Iter Criminis: Cogitação, Atos Preparatórios, Execução, Consumação e Tentativa (CP 14, 15)',

E'# Tentativa, Consumação e Desistência\n\n'
'## 1. Iter criminis\n\n'
'O **iter criminis** (caminho do crime) é a **sequência de etapas** que vai da concepção mental até a consumação. Compreende:\n\n'
'1. **Cogitação** (cogitatio)\n'
'2. **Atos preparatórios** (conatus remotus)\n'
'3. **Atos de execução** (conatus proximus)\n'
'4. **Consumação**\n'
'5. **Exaurimento** (post factum)\n\n'
'## 2. Cogitação\n\n'
'**Conceito:** a ideia criminosa na mente do agente.\n\n'
'**Penalmente irrelevante:** *"cogitationis poenam nemo patitur"* — ninguém é punido por pensar.\n\n'
'## 3. Atos Preparatórios\n\n'
'**Conceito:** atos que **antecedem a execução**, criando as condições para o crime (comprar arma, observar a vítima, traçar plano).\n\n'
'**Regra:** **impuníveis**.\n\n'
'**Exceções (tipificados autonomamente):**\n'
'- **Associação criminosa** (CP 288) — o ajuste é o próprio crime\n'
'- **Petrechos para falsificação de moeda** (CP 291)\n'
'- **Posse de explosivo** (Lei 10.826/03)\n\n'
'Quando tipificados autonomamente, deixam de ser "atos preparatórios" para serem **crimes consumados**.\n\n'
'## 4. Atos de Execução\n\n'
'**Conceito:** início concreto da realização do verbo típico — agredir a vítima, sacar a arma, romper a porta.\n\n'
'**Distinção entre preparação e execução** (questão central):\n\n'
'**a) Teoria Subjetiva:** considera a vontade do agente. **Crítica:** insegurança jurídica.\n\n'
'**b) Teoria Objetivo-Formal (adotada pela doutrina majoritária):** atos de execução começam quando o agente **inicia a realização do verbo típico**.\n\n'
'**c) Teoria Objetivo-Material:** atos de execução começam quando há ofensa próxima ao bem jurídico.\n\n'
'## 5. Consumação\n\n'
'### 5.1. Conceito\n\n'
'**CP art. 14, I:** *"Diz-se o crime consumado, quando nele se reúnem todos os elementos de sua definição legal."*\n\n'
'### 5.2. Momento da consumação\n\n'
'**a) Crimes materiais:** com a produção do **resultado naturalístico** (morte no homicídio).\n\n'
'**b) Crimes formais:** com a **conduta**, dispensando o resultado (extorsão consuma-se com a exigência).\n\n'
'**c) Crimes de mera conduta:** com a **conduta** (violação de domicílio).\n\n'
'**d) Crimes permanentes:** a consumação se prolonga no tempo (sequestro).\n\n'
'**e) Crimes habituais:** com a **reiteração** que caracterize habitualidade.\n\n'
'## 6. Tentativa (CP 14, II)\n\n'
'### 6.1. Conceito\n\n'
'**CP art. 14, II:** *"diz-se o crime tentado, quando, iniciada a execução, não se consuma por circunstâncias alheias à vontade do agente"*.\n\n'
'### 6.2. Elementos\n\n'
'1. **Início de execução**\n'
'2. **Não consumação**\n'
'3. **Causa alheia à vontade do agente**\n\n'
'### 6.3. Pena (CP 14, parágrafo único)\n\n'
'*"Salvo disposição em contrário, pune-se a tentativa com a pena correspondente ao crime consumado, diminuída de um a dois terços."*\n\n'
'### 6.4. Espécies\n\n'
'**a) Tentativa perfeita (acabada / crime falho):** o agente esgota todos os meios de execução, mas não consuma. Ex: descarrega arma na vítima, mas ela não morre.\n\n'
'**b) Tentativa imperfeita (inacabada):** o agente é interrompido antes de esgotar os meios. Ex: foi imobilizado durante o ataque.\n\n'
'**c) Tentativa branca (incruenta):** não atinge a vítima (vítima ilesa).\n\n'
'**d) Tentativa cruenta:** atinge a vítima, mas sem consumar (vítima sobrevive a lesão grave).\n\n'
'## 7. Crimes que não admitem tentativa\n\n'
'### 7.1. Crimes culposos\n\n'
'A tentativa exige **dolo**. Sem dolo, não há plano deliberado de produzir o resultado.\n\n'
'### 7.2. Crimes preterdolosos\n\n'
'Têm dolo no antecedente + culpa no consequente. Não cabe tentativa do resultado culposo agravador.\n\n'
'### 7.3. Crimes habituais\n\n'
'Exigem reiteração. Ato único não é típico.\n\n'
'### 7.4. Contravenções penais\n\n'
'**LCP art. 4º:** *"Não é punível a tentativa de contravenção."*\n\n'
'### 7.5. Crimes unissubsistentes\n\n'
'Aqueles em que a execução ocorre em **um único ato** — não admite fracionamento (injúria verbal).\n\n'
'### 7.6. Crimes omissivos próprios\n\n'
'A omissão se consuma instantaneamente — não há "iter" para tentar.\n\n'
'### 7.7. Crimes de atentado\n\n'
'Os próprios verbos típicos já punem como consumação a conduta tentada. Ex: CP 352 (evasão mediante violência).\n\n'
'## 8. Desistência Voluntária (CP 15)\n\n'
'### 8.1. Conceito\n\n'
'**CP art. 15:** *"O agente que, voluntariamente, desiste de prosseguir na execução ou impede que o resultado se produza, só responde pelos atos já praticados."*\n\n'
'### 8.2. Requisitos\n\n'
'1. **Iniciada execução** (não cabe na cogitação ou preparação)\n'
'2. **Desistência voluntária** (sem coação externa)\n'
'3. **Não consumação** do crime\n\n'
'### 8.3. Diferença com tentativa\n\n'
'| Aspecto | Tentativa | Desistência |\n'
'|---|---|---|\n'
'| Causa da não consumação | Externa (alheia à vontade) | Interna (vontade do agente) |\n'
'| Responsabilidade | Pelo crime tentado | Apenas pelos atos já praticados |\n'
'| Redução de pena | 1/3 a 2/3 | Conforme atos já praticados |\n\n'
'### 8.4. Voluntariedade x espontaneidade\n\n'
'A desistência precisa ser **voluntária**, não necessariamente **espontânea**. Pode ser por aviso de terceiros, arrependimento moral, medo de ser pego — desde que **não forçada**.\n\n'
'## 9. Arrependimento Eficaz (CP 15)\n\n'
'### 9.1. Conceito\n\n'
'O agente **já terminou a execução** mas **impede o resultado** (após o tiro, leva a vítima ao hospital para salvá-la).\n\n'
'### 9.2. Requisitos\n\n'
'1. Execução já terminada (tentativa perfeita virtual)\n'
'2. Ato positivo do agente que impede o resultado\n'
'3. Eficácia (resultado efetivamente não ocorre)\n\n'
'### 9.3. Consequência\n\n'
'Responde apenas pelos **atos já praticados**.\n\n'
'## 10. Arrependimento Posterior (CP 16)\n\n'
'### 10.1. Conceito\n\n'
'**CP art. 16:** *"Nos crimes cometidos sem violência ou grave ameaça à pessoa, reparado o dano ou restituída a coisa, até o recebimento da denúncia ou da queixa, por ato voluntário do agente, a pena será reduzida de um a dois terços."*\n\n'
'### 10.2. Requisitos\n\n'
'1. Crime sem violência ou grave ameaça\n'
'2. Reparação do dano ou restituição\n'
'3. Antes do recebimento da denúncia/queixa\n'
'4. Ato voluntário do agente\n\n'
'### 10.3. Consequência\n\n'
'**Causa de redução** da pena de 1/3 a 2/3. **Não é causa de extinção da punibilidade.**\n\n'
'### 10.4. Aplicabilidade\n\n'
'Aplica-se especialmente a:\n'
'- Furto\n'
'- Estelionato\n'
'- Apropriação indébita\n'
'- Sonegação fiscal (com regras próprias)\n\n'
'**NÃO se aplica a:** roubo, extorsão, latrocínio, sequestro (têm violência).\n\n'
'## 11. Quadro comparativo\n\n'
'| Instituto | Momento | Causa | Consequência |\n'
'|---|---|---|---|\n'
'| Tentativa | Antes da consumação | Externa | Pena reduzida 1/3 a 2/3 |\n'
'| Desistência | Durante a execução | Voluntária | Responde só pelos atos já praticados |\n'
'| Arrependimento eficaz | Após execução, antes da consumação | Voluntária + eficaz | Responde só pelos atos já praticados |\n'
'| Arrependimento posterior | Após consumação, antes da denúncia | Voluntária + reparação | Pena reduzida 1/3 a 2/3 |\n\n'
'## 12. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Cogitação é punida" ❌\n'
'- "Atos preparatórios são sempre puníveis" ❌\n'
'- "Tentativa em contravenção é punida" ❌ — LCP art. 4º\n'
'- "Desistência voluntária aplica-se à tentativa" ❌ — exclui a tentativa\n'
'- "Arrependimento posterior aplica-se ao roubo" ❌ — só sem violência\n'
'- "Arrependimento posterior extingue a punibilidade" ❌ — só reduz pena\n'
'- "Tentativa perfeita = tentativa cruenta" ❌\n'
'- "Crime habitual admite tentativa" ❌\n'
'- "Voluntariedade exige espontaneidade" ❌\n\n'
'## 13. Conclusão\n\n'
'O iter criminis e seus institutos correlatos são **certos em prova de Penal**. Para concursos, dominar: (a) sequência (cogitação → preparação → execução → consumação); (b) tentativa (CP 14 II) com redução 1/3 a 2/3; (c) crimes que não admitem tentativa (culposo, contravenção, habitual, omissivo próprio); (d) desistência voluntária vs. arrependimento eficaz (CP 15) vs. arrependimento posterior (CP 16); (e) ponte de ouro (Liszt — a desistência voluntária é "ponte de ouro" para o retorno à legalidade).\n',

  'Iter criminis: cogitação (impunível) → atos preparatórios (impuníveis, salvo tipificação autônoma como associação criminosa CP 288) → atos de execução → consumação → exaurimento. TENTATIVA (CP 14 II): início de execução + não consumação + causa ALHEIA à vontade. Pena reduzida 1/3 a 2/3 (CP 14 pu). Espécies: perfeita (acabada — esgotou os meios) x imperfeita; branca (não atinge vítima) x cruenta. NÃO admitem tentativa: culposos, preterdolosos, habituais, contravenções (LCP 4º), unissubsistentes, omissivos próprios, atentado. DESISTÊNCIA VOLUNTÁRIA (CP 15 primeira parte): durante a execução, agente desiste por vontade — responde só pelos atos já praticados. ARREPENDIMENTO EFICAZ (CP 15 segunda parte): após esgotar execução, agente impede o resultado — idem. Voluntariedade ≠ espontaneidade. ARREPENDIMENTO POSTERIOR (CP 16): crime SEM VIOLÊNCIA/grave ameaça + reparação até recebimento da denúncia → reduz pena 1/3 a 2/3 (não extingue).'
);

