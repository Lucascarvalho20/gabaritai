E'# Crime Impossível\n\n'
'## 1. Conceito\n\n'
'**Crime impossível** (também chamado **tentativa inidônea** ou **quase-crime**) ocorre quando, apesar de o agente praticar a conduta com a intenção de cometer o crime, este **jamais poderia se consumar** em razão da:\n\n'
'- **Ineficácia absoluta do meio** OU\n'
'- **Impropriedade absoluta do objeto**\n\n'
'É instituto que afasta a punibilidade por **inexistência de risco real** ao bem jurídico.\n\n'
'## 2. Fundamento legal\n\n'
'**CP art. 17:** *"Não se pune a tentativa quando, por ineficácia absoluta do meio ou por absoluta impropriedade do objeto, é impossível consumar-se o crime."*\n\n'
'## 3. Teorias\n\n'
'### 3.1. Teoria Objetiva (adotada pelo CP)\n\n'
'O crime impossível ocorre quando, **objetivamente**, é impossível a consumação. Adota-se a **teoria objetiva temperada** — exige-se **absoluta** impossibilidade.\n\n'
'**Pune-se:** quando a impossibilidade é **relativa** (havia chance real, ainda que mínima).\n'
'**Não se pune:** quando a impossibilidade é **absoluta**.\n\n'
'### 3.2. Teoria Subjetiva (não adotada)\n\n'
'Considera apenas a **intenção** do agente — puniria sempre que houvesse vontade criminosa, ainda que impossível objetivamente. Rejeitada por desrespeito ao princípio da lesividade.\n\n'
'### 3.3. Teoria Sintomática (não adotada)\n\n'
'Pune o agente pela **periculosidade revelada** — mesmo o crime impossível seria punível como demonstração de animus criminal.\n\n'
'## 4. Ineficácia Absoluta do Meio\n\n'
'### 4.1. Conceito\n\n'
'O instrumento utilizado pelo agente é **incapaz de produzir o resultado**, em qualquer circunstância.\n\n'
'### 4.2. Exemplos\n\n'
'- Atirar com **arma sem munição** (verificável previamente — se o agente sabia, é fato atípico; se não sabia, é crime impossível)\n'
'- Tentar matar com **veneno em dose subletal** quando comprovadamente incapaz de matar qualquer pessoa\n'
'- Tentar abortar com **substância inócua**\n'
'- **Pistola de brinquedo** para tentativa de homicídio\n\n'
'### 4.3. Ineficácia relativa\n\n'
'**Punível como tentativa.** Ex: arma com poucas balas (pode atingir, mas talvez não); veneno em dose talvez insuficiente.\n\n'
'### 4.4. Critério da absolutidade\n\n'
'O meio é **absolutamente** ineficaz quando, em **nenhuma hipótese**, produziria o resultado. Se em **alguma hipótese** poderia funcionar, é relativamente ineficaz (tentativa punível).\n\n'
'## 5. Impropriedade Absoluta do Objeto\n\n'
'### 5.1. Conceito\n\n'
'O **objeto material** sobre o qual recai a conduta é **inadequado** ou **inexistente** para a configuração do crime.\n\n'
'### 5.2. Exemplos\n\n'
'- **Atirar em cadáver pensando estar vivo** (vítima já estava morta) — homicídio impossível\n'
'- **Subtrair coisa própria pensando ser alheia** — furto impossível\n'
'- **Tentar abortar mulher que não está grávida** — aborto impossível\n'
'- **Apropriar-se de bem sem dono (res nullius)** — apropriação impossível\n\n'
'### 5.3. Impropriedade relativa\n\n'
'Punível como tentativa. Ex: tentar furtar carteira de pessoa que momentaneamente não a tinha consigo, mas costumava ter.\n\n'
'## 6. Reação do Estado: medidas de segurança?\n\n'
'O crime impossível **não gera responsabilidade penal**. O agente não responde por crime. **Não cabe medida de segurança** sobre quem comete crime impossível.\n\n'
'## 7. Confronto: crime impossível x tentativa\n\n'
'| Aspecto | Crime Impossível | Tentativa |\n'
'|---|---|---|\n'
'| Possibilidade objetiva | Absolutamente impossível | Possível, mas não consumada |\n'
'| Risco ao bem jurídico | Inexistente | Existente |\n'
'| Punição | Não punível (CP 17) | Pena reduzida 1/3 a 2/3 (CP 14 pu) |\n\n'
'## 8. Crime putativo\n\n'
'### 8.1. Conceito\n\n'
'**Crime putativo** é aquele em que o agente **acredita** estar cometendo crime, mas a conduta **não é típica** (ou é atípica por outras razões).\n\n'
'### 8.2. Espécies\n\n'
'**a) Crime putativo por erro de tipo:** o agente erra sobre elemento do tipo (acredita que está fazendo algo errado, mas não é). Ex: relação consensual com pessoa que aparenta menos de 14 anos mas tem 17 (não é estupro de vulnerável).\n\n'
'**b) Crime putativo por erro de proibição (delito imaginário):** o agente acredita que sua conduta é crime, mas não é. Ex: praticar ato que considera proibido mas a lei não criminaliza.\n\n'
'**c) Crime putativo por obra do agente provocador (Súmula 145 STF):** quando há **flagrante preparado** ou **provocado** pela polícia, e o crime jamais poderia se consumar por estar sob controle policial.\n\n'
'### 8.3. Súmula 145 STF\n\n'
'*"Não há crime, quando a preparação do flagrante pela polícia torna impossível a sua consumação."*\n\n'
'**Aplicação:**\n'
'- **Flagrante PREPARADO:** policial induz à prática do crime + acompanha tudo, impedindo consumação → crime impossível\n'
'- **Flagrante ESPERADO:** policial **apenas aguarda** a prática (sem induzir) → tentativa ou crime consumado, conforme o caso (NÃO se aplica a Súmula 145)\n\n'
'## 9. Casuística importante\n\n'
'### 9.1. Furto em estabelecimento monitorado por câmeras\n\n'
'**Antiga jurisprudência STJ:** considerava **crime impossível** porque o sistema impedia a consumação.\n\n'
'**Súmula 567 STJ (2015):** *"Sistema de vigilância realizado por monitoramento eletrônico ou por existência de segurança no interior de estabelecimento comercial, por si só, não torna impossível a configuração do crime de furto."*\n\n'
'**Conclusão:** sistema de vigilância **não** caracteriza crime impossível automaticamente. Pode haver tentativa ou consumação.\n\n'
'### 9.2. Quase-crime militar\n\n'
'CPM tem regras próprias (art. 32), mas com tratamento similar.\n\n'
'### 9.3. Crime impossível por inidoneidade do sujeito ativo\n\n'
'Quando o agente **não pode juridicamente** cometer o crime (ex: particular tenta praticar crime próprio de servidor público). Em regra, não há crime — não se pune.\n\n'
'## 10. Crime Impossível e Concurso de Pessoas\n\n'
'Se o crime é impossível para o autor, **não há crime para o partícipe**. Aplicação do princípio da acessoriedade.\n\n'
'## 11. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
