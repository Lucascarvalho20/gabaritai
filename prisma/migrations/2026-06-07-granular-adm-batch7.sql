E'# Limites do Poder Discricionário\n\n'
'## 1. Conceito de discricionariedade\n\n'
'A discricionariedade é a **margem de liberdade** que a lei concede ao agente administrativo para, diante de um caso concreto, escolher entre alternativas legítimas a solução que melhor atenda ao interesse público. Não é arbitrariedade — é liberdade dentro de balizas legais.\n\n'
'Como ensina Celso Antônio Bandeira de Mello, *"a discricionariedade é a margem de liberdade que remanesça ao administrador para eleger, segundo critérios consistentes de razoabilidade, um, dentre pelo menos dois comportamentos cabíveis, perante cada caso concreto"*.\n\n'
'## 2. Fundamento\n\n'
'A discricionariedade tem três fontes:\n\n'
'1. **Linguagem da lei vaga (conceitos jurídicos indeterminados):** "interesse público", "moralidade", "urgência", "bom serviço"\n'
'2. **Atribuição expressa pela lei** ("poderá", "a critério da Administração")\n'
'3. **Lacuna técnica:** quando a escolha depende de avaliação técnica especializada\n\n'
'## 3. Elementos vinculados x discricionários\n\n'
'Todo ato administrativo tem 5 elementos (Lei 4.717/65 art. 2º): **competência, finalidade, forma, motivo e objeto**.\n\n'
'- **Competência, finalidade e forma:** sempre **vinculados** (não há discricionariedade)\n'
'- **Motivo e objeto:** podem ser vinculados ou discricionários\n\n'
'A discricionariedade incide apenas sobre motivo e/ou objeto, e somente quando a lei autorizar.\n\n'
'## 4. Mérito administrativo\n\n'
'**Mérito administrativo** é a valoração subjetiva da **conveniência e oportunidade** que o administrador faz dentro do espaço discricionário. É o "miolo" da discricionariedade.\n\n'
'Tradicionalmente, o mérito é **insindicável pelo Judiciário** — o juiz não pode substituir a Administração na escolha de conveniência. Porém, essa regra tem sido **fortemente temperada** pela jurisprudência atual.\n\n'
'## 5. Limites tradicionais à discricionariedade\n\n'
'### 5.1. Legalidade\n\n'
'O ato discricionário só é válido se respeitar a lei. A lei delimita o "espaço" da discricionariedade.\n\n'
'### 5.2. Finalidade pública\n\n'
'Mesmo discricionário, o ato deve buscar o interesse público (e a finalidade específica prevista na norma). Desvio = nulidade.\n\n'
'### 5.3. Competência\n\n'
'Só o agente competente pode exercer a discricionariedade. Ato de agente incompetente é nulo, mesmo que materialmente acertado.\n\n'
'### 5.4. Forma\n\n'
'Ato discricionário sujeita-se à forma exigida em lei.\n\n'
'### 5.5. Motivo\n\n'
'O motivo (suporte fático e jurídico) deve existir e ser verdadeiro. Teoria dos motivos determinantes (vista no princípio da motivação) aplica-se aqui.\n\n'
'## 6. Limites modernos — controle judicial ampliado\n\n'
'O Direito Administrativo contemporâneo ampliou o controle:\n\n'
'### 6.1. Razoabilidade e proporcionalidade\n\n'
'O ato discricionário deve ser **razoável** (adequado ao fim) e **proporcional** (necessário, adequado, proporcional em sentido estrito). Atos irrazoáveis são nulos, mesmo no espaço discricionário (STF, STJ — consolidado).\n\n'
'### 6.2. Eficiência\n\n'
'A escolha discricionária deve buscar eficiência (CF 37, caput, EC 19/98). Decisões manifestamente ineficientes podem ser anuladas.\n\n'
'### 6.3. Moralidade\n\n'
'A escolha deve respeitar padrões éticos. Decisão discricionária imoral é nula (CF 37).\n\n'
'### 6.4. Impessoalidade\n\n'
'Não pode haver favoritismo ou perseguição.\n\n'
'### 6.5. Controle pelo motivo\n\n'
'O motivo declarado deve ser verdadeiro e suficiente (teoria dos motivos determinantes).\n\n'
'### 6.6. Controle da omissão\n\n'
'O Judiciário pode determinar à Administração que adote medidas concretas, mesmo discricionárias, em casos de **inércia injustificada** que viole direitos fundamentais (mínimo existencial, judicialização de saúde, vagas em creche).\n\n'
'## 7. Desvio de finalidade\n\n'
'### 7.1. Conceito\n\n'
'Desvio de finalidade (ou desvio de poder, *détournement de pouvoir*) ocorre quando o agente, embora competente, age **com motivo aparente lícito**, mas com **intenção real diversa** — buscando finalidade distinta da prevista na lei.\n\n'
'### 7.2. Fundamento normativo\n\n'
'**Lei 4.717/65 art. 2º, "e":** *"o desvio de finalidade [verifica-se] quando o agente pratica o ato visando a fim diverso daquele previsto, explícita ou implicitamente, na regra de competência"*.\n\n'
'### 7.3. Modalidades\n\n'
'**a) Desvio para fim privado:** o agente busca interesse pessoal, vingança, favorecimento\n\n'
'**b) Desvio para fim público diverso:** o agente busca interesse público, mas diferente do previsto pela norma (ex.: usar desapropriação para "obra pública" quando, na verdade, o objetivo é punir o proprietário ou alterar a vizinhança)\n\n'
'Ambos os desvios anulam o ato.\n\n'
'### 7.4. Exemplo clássico\n\n'
'**STF MS 23.474:** servidor exonerado de cargo em comissão por "perda de confiança". Investigou-se: a verdadeira razão era retaliação após denúncia de irregularidade. Ato anulado por desvio de finalidade.\n\n'
'**STJ REsp 39.353:** remoção ex officio de servidor para "necessidade do serviço". Provada perseguição política. Anulado.\n\n'
'### 7.5. Prova do desvio\n\n'
'A prova do desvio é **indireta**, baseada em **indícios convergentes**: comportamento prévio, declarações, contexto, ausência de plausibilidade do motivo alegado. Cabe a quem alega.\n\n'
'## 8. Discricionariedade técnica\n\n'
'Categoria diferenciada: quando a escolha exige avaliação técnica especializada (ANS, ANVISA, Anatel). O Judiciário tradicionalmente é mais deferente, mas pode controlar:\n\n'
'- Razoabilidade técnica\n'
'- Aderência ao estado da arte\n'
'- Proporcionalidade\n\n'
'## 9. Conceitos jurídicos indeterminados\n\n'
'Hely Lopes Meirelles tratava CJI como espaço discricionário. A doutrina moderna (Eros Roberto Grau, Carlos Ari Sundfeld) distingue:\n\n'
'- **CJI** envolve interpretação (busca da única solução correta)\n'
'- **Discricionariedade** envolve escolha entre soluções legítimas\n\n'
'Mas, na prática judicial, conceitos como "interesse público" e "moralidade" mantêm margem ampla de apreciação.\n\n'
'## 10. Limites quanto à reserva legal\n\n'
'A discricionariedade jamais pode ser usada para:\n\n'
'- Criar tributo (reserva legal absoluta — CF 150, I)\n'
'- Criar crime ou pena (CF 5º, XXXIX)\n'
'- Criar cargo, função, ônus excessivo sem lei\n'
'- Limitar direito fundamental sem lei\n\n'
'## 11. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Discricionariedade é arbitrariedade" ❌ — uma é dentro da lei; outra é fora dela\n'
'- "Mérito administrativo não pode ser objeto de controle judicial" ❌ — pode ser controlado quanto à razoabilidade, proporcionalidade, moralidade, motivo\n'
'- "Conveniência e oportunidade são insindicáveis" ❌ — a doutrina moderna admite controle pela razoabilidade\n'
'- "Desvio de finalidade é vício de competência" ❌ — é vício de **finalidade**\n'
'- "Ato discricionário não tem motivo" ❌ — sempre tem motivo; só há liberdade na escolha do motivo\n'
'- "Discricionariedade abrange competência, forma e finalidade" ❌ — esses são sempre vinculados\n\n'
'## 12. Conclusão\n\n'
'A discricionariedade é o **espaço de liberdade** do administrador para realizar o interesse público diante de situações concretas. Mas é uma liberdade **balizada**: legalidade, finalidade, razoabilidade, proporcionalidade, motivação, moralidade. O controle judicial é amplo sobre os limites, embora respeite o núcleo do mérito quando este se mantiver dentro de margens legítimas. Para concursos policiais, dominar a distinção mérito x legalidade, o conceito de desvio de finalidade e os exemplos jurisprudenciais clássicos resolve a maior parte das questões.\n',

  'Discricionariedade é margem de liberdade dada pela lei (≠ arbitrariedade). Incide só sobre motivo e objeto (nunca competência, finalidade, forma). Mérito = conveniência e oportunidade; tradicionalmente insindicável, mas o controle moderno alcança razoabilidade, proporcionalidade, moralidade, motivo verdadeiro (teoria dos motivos determinantes). Desvio de finalidade (Lei 4.717/65 art. 2º "e") = agente busca fim diverso do previsto (privado ou público diverso). Discricionariedade NÃO permite criar tributo, crime, pena, cargo. Jurisprudência ampliou controle judicial. Ex: STF MS 23.474.'
