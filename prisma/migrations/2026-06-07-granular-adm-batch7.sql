SELECT upsert_material(
  'direito-administrativo',
  'Princípio da Especialidade',
  'Princípio da Especialidade: vinculação dos entes da Administração Indireta a suas finalidades legais',

E'# Princípio da Especialidade\n\n'
'## 1. Conceito\n\n'
'O princípio da especialidade impõe que as **pessoas jurídicas integrantes da Administração Indireta** (autarquias, fundações públicas, empresas públicas e sociedades de economia mista) **só podem exercer as atividades para as quais foram criadas por lei**. Estão **vinculadas ao fim específico (finalidade legal)** que motivou sua criação.\n\n'
'Trata-se de **manifestação concreta dos princípios da legalidade e da finalidade** aplicada ao plano da descentralização administrativa.\n\n'
'## 2. Fundamento normativo\n\n'
'### 2.1. Constituição Federal\n\n'
'- **Art. 37, XIX:** *"Somente por lei específica poderá ser criada autarquia e autorizada a instituição de empresa pública, de sociedade de economia mista e de fundação..."*\n'
'- **Art. 37, XX:** *"Depende de autorização legislativa, em cada caso, a criação de subsidiárias das entidades mencionadas no inciso anterior, assim como a participação de qualquer delas em empresa privada"*\n\n'
'Conclusão: como a entidade nasce por lei, **só pode agir nos limites dessa lei**.\n\n'
'### 2.2. Decreto-Lei 200/67 (Reforma Administrativa)\n\n'
'- **Art. 5º:** define cada espécie da Administração Indireta com referência expressa à finalidade legal\n\n'
'### 2.3. Doutrina\n\n'
'Hely Lopes Meirelles, Maria Sylvia Di Pietro e Celso Antônio Bandeira de Mello classificam a especialidade como **princípio fundamental** da Administração Indireta.\n\n'
'## 3. Alcance\n\n'
'### 3.1. Limitação à atuação\n\n'
'A entidade só pode atuar dentro de sua **finalidade institucional**:\n\n'
'- **IBAMA** não pode regular trânsito\n'
'- **INSS** não pode arrecadar IPTU\n'
'- **Banco do Brasil** não pode prestar serviço público de saúde\n'
'- **Petrobras** não pode ofertar planos previdenciários\n\n'
'A atuação fora da finalidade caracteriza **vício de competência** ou **desvio de finalidade**, sendo o ato nulo (Lei 4.717/65 art. 2º).\n\n'
'### 3.2. Limitação à criação de subsidiárias\n\n'
'O STF (RE 562.276) firmou: a autorização legislativa para criar subsidiárias **não precisa ser específica** para cada subsidiária — basta autorização **genérica** na lei criadora da estatal-matriz.\n\n'
'### 3.3. Limitação à modificação\n\n'
'Alterar a finalidade da entidade exige **lei específica** (CF art. 37, XIX), assim como sua extinção (princípio do paralelismo de formas).\n\n'
'### 3.4. Limitação à terceirização\n\n'
'A entidade da Administração Indireta pode terceirizar atividades-meio, mas não pode terceirizar a atividade-fim (que é justamente sua especialidade), sob pena de fraude ao princípio.\n\n'
'## 4. Especialidade x discricionariedade administrativa\n\n'
'O princípio reduz substancialmente a margem de discricionariedade da entidade. Diferente da Administração Direta — que tem competência geral — a entidade descentralizada é **especializada por definição**. Não cabe a ela "buscar oportunidades de mercado" ou "diversificar" livremente.\n\n'
'Mesmo as estatais (EP/SEM), que atuam em regime de direito privado, estão vinculadas à finalidade legal. A Lei 13.303/16 (Estatuto das Estatais) reforça isso ao exigir cumprimento de função social, governança, plano estratégico alinhado à finalidade etc.\n\n'
'## 5. Distinção entre especialidade e capacidade civil ampla\n\n'
'No direito privado, a regra é a **capacidade ampla** (pode-se fazer tudo que a lei não proíba). No direito administrativo, especialmente para a Administração Indireta, vige o oposto: **só se pode o que a lei autoriza expressamente**.\n\n'
'Mesmo a EP e a SEM, que se submetem ao direito privado em suas operações, têm como pressuposto a finalidade legal — não são empresas livres no mercado.\n\n'
'## 6. Especialidade na criação de empresas-mães e subsidiárias\n\n'
'### 6.1. Empresa-mãe\n\n'
'A criação exige:\n'
'- **Lei específica autorizativa** (CF 37, XIX)\n'
'- **Registro civil ou comercial** (CC art. 45) — a personalidade jurídica nasce do registro, não da lei\n'
'- **Finalidade institucional clara** na lei autorizativa\n\n'
'### 6.2. Subsidiárias\n\n'
'A criação exige:\n'
'- **Autorização legislativa** (CF 37, XX) — pode ser genérica (STF RE 562.276)\n'
'- **Vinculação à finalidade da empresa-mãe**\n'
'- **Não criação de "rede" para escapar do controle público**\n\n'
'## 7. Aplicações concretas\n\n'
'### 7.1. Ação fora da finalidade\n\n'
'Caso (hipotético típico de prova): autarquia ambiental adquire shopping center e passa a explorá-lo comercialmente. Ato **nulo** por desvio de finalidade — não há previsão legal de exploração comercial em sua lei criadora.\n\n'
'### 7.2. Convênios e parcerias\n\n'
'A entidade pode celebrar convênios com outras entidades, desde que o objeto se alinhe à finalidade. Não pode usar convênio para extrapolar competência.\n\n'
'### 7.3. Privatização e mudança de finalidade\n\n'
'Para extinguir uma EP ou SEM, é necessária **autorização legislativa** (paralelismo de formas — STF ADI 5.624). Ato de privatização não pode dispensar lei.\n\n'
'## 8. Consequência da violação\n\n'
'A atuação fora da finalidade enseja:\n\n'
'- **Nulidade do ato administrativo** (Lei 4.717/65 art. 2º, "e" — desvio de finalidade)\n'
'- **Ação popular** para anulação (CF art. 5º, LXXIII)\n'
'- **Ação civil pública**\n'
'- **Responsabilização do dirigente** (Lei 8.429/92 — improbidade administrativa, quando configurada)\n'
'- **Controle do TCU** quanto à legalidade da despesa\n\n'
'## 9. Especialidade e o Sistema S\n\n'
'O Sistema S (SESI, SENAI, SESC etc.) não integra a Administração Indireta, mas como recebe verbas parafiscais, está submetido a fins legalmente delimitados. A jurisprudência (STF RE 789.874) confirmou autonomia maior — não exige concurso —, mas a finalidade institucional permanece amarra obrigatória.\n\n'
'## 10. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Autarquia tem competência ampla para qualquer atividade" ❌ — só dentro de sua finalidade legal\n'
'- "Subsidiária pode ser criada por simples ato administrativo" ❌ — exige autorização legislativa\n'
'- "Empresas estatais não estão sujeitas ao princípio da especialidade" ❌ — estão\n'
'- "Especialidade é princípio implícito" — controvertido; muitos manuais classificam como **explícito** (CF 37, XIX-XX)\n'
'- "Lei pode autorizar genericamente a criação de várias subsidiárias" ✅ (STF RE 562.276)\n\n'
'## 11. Conclusão\n\n'
'O princípio da especialidade é a **estaca que prende cada entidade descentralizada à sua finalidade**, impedindo crescimento desordenado, concorrência indevida com o setor privado e fuga ao controle democrático. Em concursos, é cobrado especialmente em conjunto com a Administração Indireta — saber que **lei específica cria e lei específica modifica/extingue**, e que **subsidiária precisa de autorização legislativa**, garante acertos.\n',

  'Princípio da Especialidade vincula as entidades da Administração Indireta (autarquias, fundações, EP, SEM) às finalidades específicas para que foram criadas por lei (CF 37 XIX-XX). Atuação fora da finalidade = desvio = ato nulo (Lei 4.717/65 art. 2º "e"). Criação exige lei específica; subsidiárias exigem autorização legislativa (pode ser genérica — STF RE 562.276). Mesmo EP/SEM em regime privado estão vinculadas. Extinção segue paralelismo de formas — exige lei (STF ADI 5.624). Sistema S tem fins delimitados, mas autonomia (STF RE 789.874).'
);

