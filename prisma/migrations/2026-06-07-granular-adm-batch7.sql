'- **Finalidade** (desvio)\n'
'- **Motivo** (inexistente, falso)\n'
'- **Objeto** (ilícito, impossível)\n\n'
'## 7. Cassação\n\n'
'Forma específica de desfazimento: **cessação por descumprimento de condições** pelo beneficiário. Ex.: licença para construir cassada porque o titular descumpriu o projeto aprovado.\n\n'
'## 8. Contraposição (caducidade)\n\n'
'**Caducidade** é o desfazimento do ato por **superveniência de norma jurídica incompatível**. Ex.: permissão de uso de área pública cassada porque nova lei tornou a atividade incompatível.\n\n'
'## 9. Limites da autotutela\n\n'
'### 9.1. Limites materiais\n\n'
'- **Boa-fé do destinatário** (Lei 9.784/99 art. 54)\n'
'- **Decadência de 5 anos** para atos favoráveis\n'
'- **Direitos adquiridos**\n'
'- **Coisa julgada administrativa** (atos com preclusão)\n'
'- **Proteção da confiança legítima**\n\n'
'### 9.2. Limites procedimentais\n\n'
'- **Contraditório e ampla defesa** (CF 5º, LV; Súmula Vinculante 3 STF)\n'
'- **Motivação adequada** (Lei 9.784/99 art. 50)\n'
'- **Razoabilidade**\n\n'
