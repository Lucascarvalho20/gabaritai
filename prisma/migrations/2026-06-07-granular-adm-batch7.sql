SELECT upsert_material(
  'direito-administrativo',
  'Princípio da Segurança Jurídica',
  'Princípio da Segurança Jurídica: estabilidade das relações administrativas e proteção da confiança',

E'# Princípio da Segurança Jurídica\n\n'
'## 1. Conceito\n\n'
'A segurança jurídica é um **princípio implícito da Constituição** que assegura a **estabilidade, previsibilidade e confiabilidade das relações jurídicas** estabelecidas entre o Estado e os particulares.\n\n'
'Compreende três dimensões fundamentais:\n\n'
'1. **Estabilidade das situações constituídas** — direitos adquiridos, atos jurídicos perfeitos, coisa julgada não podem ser desfeitos arbitrariamente\n'
'2. **Proteção da confiança legítima** — o particular tem direito a confiar em manifestações estatais\n'
'3. **Boa-fé objetiva** — orientadora das relações Estado-cidadão\n\n'
'## 2. Fundamento normativo\n\n'
'### 2.1. Constituição Federal (implícita e expressa)\n\n'
'- **Preâmbulo:** segurança como valor\n'
'- **Art. 1º, caput:** Estado Democrático de Direito (a segurança é elemento essencial)\n'
'- **Art. 5º, XXXVI:** *"A lei não prejudicará o direito adquirido, o ato jurídico perfeito e a coisa julgada"*\n'
'- **Art. 5º, XL:** *"A lei penal não retroagirá, salvo para beneficiar o réu"*\n'
'- **Art. 150, III, a:** princípio da irretroatividade tributária\n\n'
'### 2.2. Lei 9.784/99 — Processo Administrativo Federal\n\n'
'- **Art. 2º:** segurança jurídica está expressamente entre os princípios da Administração\n'
'- **Art. 2º, parágrafo único, XIII:** *"interpretação da norma administrativa da forma que melhor garanta o atendimento do fim público a que se dirige, vedada aplicação retroativa de nova interpretação"*\n'
'- **Art. 54:** prazo decadencial de 5 anos para a Administração anular atos administrativos que produzam efeitos favoráveis a destinatários de boa-fé\n'
'- **Art. 55:** convalidação de atos com vício sanável que não causem prejuízo ao interesse público nem a terceiros\n\n'
'### 2.3. LINDB (Decreto-Lei 4.657/42), com a redação dada pela Lei 13.655/18\n\n'
'- **Art. 21:** nova interpretação só atinge atos futuros\n'
'- **Art. 22:** atos administrativos devem considerar consequências práticas\n'
'- **Art. 23:** decisão que estabelecer nova interpretação ou orientação geral deverá prever regime de transição\n'
'- **Art. 24:** revisão de atos não invalidará situações constituídas com base em orientação geral à época\n\n'
'## 3. Dimensões e aplicações\n\n'
'### 3.1. Estabilidade dos atos administrativos\n\n'
'Atos administrativos, mesmo viciados, podem ganhar estabilidade pelo decurso do tempo:\n\n'
'- **Decadência (5 anos):** Lei 9.784/99 art. 54 — a Administração não pode anular atos que produziram efeitos favoráveis a terceiros de boa-fé depois de 5 anos contados da sua prática (salvo má-fé). Esse prazo é decadencial.\n'
'- **Convalidação:** Lei 9.784/99 art. 55 — vícios sanáveis (forma, competência) podem ser convalidados retroativamente\n\n'
'### 3.2. Proteção da confiança legítima\n\n'
'É a dimensão subjetiva da segurança jurídica. Quando o particular **confia legitimamente** em uma manifestação estatal (orientação, súmula, prática reiterada) e organiza sua vida com base nela, essa confiança merece proteção.\n\n'
'**Pressupostos da proteção da confiança (doutrina alemã/Karoline Engel — adotada no Brasil):**\n'
'1. Manifestação estatal apta a gerar expectativa\n'
'2. Confiança subjetiva do particular\n'
'3. Comportamento concreto do particular fundado nessa confiança (disposição patrimonial, mudança de vida)\n'
'4. Boa-fé\n'
'5. Frustração da expectativa por mudança superveniente\n\n'
'**Exemplo clássico (STF MS 26.085):** beneficiários que receberam pagamento indevido durante anos por equívoco da Administração — o STF determinou que não devolvessem os valores recebidos de boa-fé, em razão da segurança jurídica e da proteção da confiança.\n\n'
'### 3.3. Vedação à retroatividade de interpretação\n\n'
'A Lei 9.784/99 art. 2º, parágrafo único, XIII, e a LINDB art. 24 vedam a aplicação retroativa de nova interpretação. Se a Administração mudou de entendimento, **só pode aplicar a nova orientação para o futuro** (princípio do tempus regit actum).\n\n'
'### 3.4. Regime de transição\n\n'
'A LINDB art. 23 exige que mudanças de orientação contemplem **regime de transição** para minimizar impactos sobre situações em curso. Não basta mudar; é preciso suavizar.\n\n'
'## 4. Distinção: segurança jurídica x proteção da confiança\n\n'
'| Aspecto | Segurança Jurídica | Proteção da Confiança |\n'
'|---|---|---|\n'
'| Dimensão | Objetiva (sistema) | Subjetiva (indivíduo) |\n'
'| Foco | Estabilidade das normas e atos | Expectativas legítimas |\n'
'| Manifestação | Direito adquirido, coisa julgada, decadência | Não devolução de valores recebidos de boa-fé |\n\n'
'Embora distinguíveis, são facetas do mesmo princípio.\n\n'
'## 5. Conflito segurança jurídica x legalidade estrita\n\n'
'O grande dilema: o ato é ilegal, mas o tempo passou e o particular confiou. Anular ou manter?\n\n'
'Soluções normativas:\n'
'- **Lei 9.784/99 art. 54:** prazo de 5 anos para anulação se houver boa-fé\n'
'- **Ponderação caso a caso:** especialmente em situações sensíveis (servidor, aposentadoria, pagamento)\n\n'
'STF (MS 24.268, MS 25.116): a Súmula 473 do STF (Administração pode anular seus próprios atos ilegais a qualquer tempo) **deve ser temperada** pela Lei 9.784/99 e pela proteção da confiança.\n\n'
'## 6. Aplicação no controle administrativo\n\n'
'**Tribunal de Contas e segurança jurídica:**\n'
'- Súmula Vinculante 3 STF: o TCU deve assegurar contraditório quando o ato puder anular ato administrativo que beneficie o interessado, **salvo apreciação inicial da legalidade de concessão de aposentadoria**\n'
'- STF revisou a posição (RE 636.553 — 2020): o TCU tem **prazo de 5 anos** para julgar a legalidade do ato inicial de concessão de aposentadoria. Após esse prazo, a coisa julgada administrativa se forma e impõe contraditório.\n\n'
'## 7. Aplicação em concursos\n\n'
'**Casos típicos:**\n'
'- Servidor admitido sem concurso há mais de 5 anos: a Administração pode anular? Em regra, **não**, por força do art. 54 da Lei 9.784/99 (salvo má-fé comprovada)\n'
'- Pagamento indevido reiterado: devolução? **Não** se houver boa-fé (Súmula 34 AGU)\n'
'- Nova interpretação de norma tributária: aplica-se a atos pretéritos? **Não**\n'
'- Aposentadoria com vício, mas concedida há 8 anos: TCU pode rever sem contraditório? **Não** (RE 636.553)\n\n'
'## 8. Tópicos de prova\n\n'
'**Pegadinhas frequentes:**\n'
'- "Administração pode anular qualquer ato ilegal a qualquer tempo" ❌ — só dentro de 5 anos para favoráveis ao destinatário de boa-fé\n'
'- "Proteção da confiança é estranha ao Direito brasileiro" ❌ — está positivada na LINDB e na Lei 9.784/99\n'
'- "Nova interpretação aplica-se retroativamente" ❌\n'
'- "Pagamento indevido de boa-fé deve ser devolvido sempre" ❌ — Súmula 34 AGU dispensa\n'
'- "Tempo nunca convalida ilegalidade" ❌ — o decurso de prazo gera decadência\n\n'
'## 9. Conclusão\n\n'
'A segurança jurídica é o **antídoto contra a instabilidade administrativa** e contra a anulação intempestiva de atos. Após a Lei 9.784/99 e, principalmente, a Lei 13.655/18 (que reformou a LINDB), o princípio ganhou força normativa explícita. Para concursos, dominar o art. 54 (decadência de 5 anos), a LINDB arts. 21-24 (regime de transição, vedação à retroatividade interpretativa) e a Súmula 473 STF temperada pela boa-fé é essencial.\n',

  'Segurança jurídica = estabilidade, previsibilidade, proteção da confiança e boa-fé. Fundamento: CF 5º XXXVI (direito adquirido, ato jurídico perfeito, coisa julgada), Lei 9.784/99 art. 2º e arts. 54-55, LINDB arts. 21-24 (Lei 13.655/18 — vedação à retroatividade interpretativa, regime de transição). Decadência de 5 anos para Administração anular atos favoráveis a beneficiário de boa-fé (art. 54). Súmula 473 STF temperada. Súmula 34 AGU: pagamento indevido de boa-fé não se devolve. RE 636.553: TCU tem 5 anos para revisar aposentadoria sem contraditório.'
