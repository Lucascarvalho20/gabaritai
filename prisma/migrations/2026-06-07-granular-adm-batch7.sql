'| Aspecto | Anulação | Revogação |\n'
'|---|---|---|\n'
'| Causa | Ilegalidade | Inconveniência |\n'
'| Natureza | Dever | Faculdade |\n'
'| Efeitos | Ex tunc | Ex nunc |\n'
'| Pode ser feita pelo Judiciário? | Sim | Não |\n'
'| Prazo | 5 anos (art. 54 — favoráveis e boa-fé) | Inexistente (mas respeita direito adquirido) |\n'
'| Direitos adquiridos | Em regra, atinge | Não atinge |\n\n'
'## 6. Convalidação (Lei 9.784/99 art. 55)\n\n'
'Convalidação é a **correção, com efeito retroativo, de ato com vício sanável**, desde que:\n\n'
'1. Não acarrete lesão ao interesse público\n'
'2. Não cause prejuízo a terceiros\n\n'
'Vícios sanáveis:\n'
'- **Forma** (defeito formal — ex.: ausência de assinatura)\n'
'- **Competência** (relativa — ex.: ato de subdelegação)\n\n'
