SELECT upsert_material(
  'direito-administrativo',
  'Princípio da Motivação',
  'Princípio da Motivação: dever de exposição dos fundamentos do ato administrativo',

E'# Princípio da Motivação\n\n'
'## 1. Conceito\n\n'
'O princípio da motivação impõe à Administração Pública o dever de **expor expressamente os pressupostos de fato e de direito** que conduziram à edição de cada ato administrativo. Não basta a Administração agir conforme a lei — ela deve **demonstrar** publicamente por que agiu daquele modo.\n\n'
'Motivar é traduzir, em linguagem inteligível, o raciocínio que liga o **suporte fático** (situação concreta), o **suporte normativo** (lei aplicável) e o **conteúdo do ato** (decisão tomada).\n\n'
'## 2. Distinção: motivo, motivação e móvel\n\n'
'É essencial separar três conceitos próximos:\n\n'
'- **Motivo:** pressuposto de fato e de direito que serve de fundamento ao ato. É **elemento do ato administrativo** (Lei 4.717/65 art. 2º, alínea "d"). Sem motivo, o ato é nulo.\n'
'- **Motivação:** **explicitação por escrito** dos motivos. É o documento, a fundamentação, a "exposição de motivos".\n'
'- **Móvel:** intenção subjetiva do agente. É psicológico, não jurídico (irrelevante para a validade do ato, salvo desvio de finalidade).\n\n'
'Exemplo: um servidor é demitido (ato).\n'
'- **Motivo:** ter praticado falta funcional grave (CF e lei prevêem demissão)\n'
'- **Motivação:** processo administrativo disciplinar que descreveu fatos, provas e enquadramento\n'
'- **Móvel:** vingança pessoal do chefe? Se for, desvio de finalidade\n\n'
'## 3. Fundamento normativo\n\n'
'### 3.1. Constituição Federal\n\n'
'- **Art. 93, IX (Judiciário):** *"Todos os julgamentos dos órgãos do Poder Judiciário serão públicos, e fundamentadas todas as decisões..."* — extensão analógica à Administração\n'
'- **Art. 93, X (administrativo nos tribunais):** *"As decisões administrativas dos tribunais serão motivadas e em sessão pública..."* — referência expressa a motivação\n'
'- **Art. 5º, XXXV, LIV, LV:** devido processo legal substantivo, ampla defesa, contraditório (todos exigem decisões motivadas)\n\n'
'### 3.2. Lei 9.784/99 (Processo Administrativo Federal)\n\n'
'- **Art. 2º, caput:** elenca a motivação entre os princípios da Administração\n'
'- **Art. 50:** *"Os atos administrativos deverão ser motivados, com indicação dos fatos e dos fundamentos jurídicos, quando:"*\n'
'  - I — neguem, limitem ou afetem direitos ou interesses;\n'
'  - II — imponham ou agravem deveres, encargos ou sanções;\n'
'  - III — decidam processos administrativos de concurso ou seleção pública;\n'
'  - IV — dispensem ou declarem a inexigibilidade de processo licitatório;\n'
'  - V — decidam recursos administrativos;\n'
'  - VI — decorram de reexame de ofício;\n'
'  - VII — deixem de aplicar jurisprudência firmada sobre a questão ou discrepem de pareceres, laudos, propostas e relatórios oficiais;\n'
'  - VIII — importem anulação, revogação, suspensão ou convalidação de ato administrativo\n\n'
'O rol é amplo e tem sido lido como **dever geral de motivação** com hipóteses excepcionais de dispensa.\n\n'
'## 4. Conteúdo da motivação adequada\n\n'
'Uma motivação adequada deve conter:\n\n'
'1. **Descrição dos fatos** (suporte fático)\n'
'2. **Indicação dos dispositivos legais** aplicáveis\n'
'3. **Demonstração da subsunção** dos fatos ao direito\n'
'4. **Justificativa da escolha** entre opções (se houve discricionariedade)\n'
'5. **Eventual referência a outros documentos** (pareceres, laudos), que se incorporam por remissão (motivação aliunde — Lei 9.784/99 art. 50, § 1º)\n\n'
'## 5. Motivação per relationem (ou aliunde)\n\n'
'A Lei 9.784/99 admite que o ato administrativo seja motivado **por referência a outro documento** já constante do processo (parecer, relatório, despacho), desde que este traga os fundamentos. Não é necessário transcrever — basta indicar com clareza.\n\n'
'Exemplo: "Adoto, como razões de decidir, o parecer da Procuradoria de fls. 23-30" — válido se o parecer for adequado e estiver acessível.\n\n'
'O STF (RE 654.432) e o STJ (REsp 1.337.612) aceitam essa modalidade desde que não comprometa o direito de defesa.\n\n'
'## 6. Motivação dos atos discricionários\n\n'
'Embora o ato discricionário tenha margem de escolha, a Administração não está dispensada de motivar — pelo contrário, é **justamente o ato discricionário que mais precisa ser motivado**, porque a motivação é o que permite controlar abusos.\n\n'
'O STF (MS 24.268) consolidou: *"A discricionariedade administrativa não é incompatível com a motivação; ao revés, exige-a, na medida em que sem motivação não há controle da discricionariedade."*\n\n'
'## 7. Vinculação aos motivos declarados (Teoria dos Motivos Determinantes)\n\n'
'A teoria, de origem francesa (Conselho de Estado), estabelece: **uma vez exposto o motivo, o ato fica vinculado a ele.** Se o motivo declarado for falso, inexistente ou juridicamente impossível, o ato é **nulo**.\n\n'
'Aplica-se mesmo a atos **discricionários** (onde a motivação seria, em tese, dispensável) e a atos onde a lei não exija expressamente a motivação. Uma vez motivado, é "preso" ao motivo.\n\n'
'**Exemplo clássico (STF MS 23.474):** servidor exonerado de cargo em comissão por suposta "perda de confiança". Comprovou-se que a verdadeira razão era retaliação política. Ato anulado, embora a exoneração ad nutum, em tese, dispense motivação.\n\n'
'## 8. Hipóteses de dispensa de motivação expressa\n\n'
'A doutrina identifica hipóteses excepcionais em que a motivação expressa é dispensável:\n\n'
'- **Atos típicos de chefia** sem repercussão patrimonial (despachos meramente ordinatórios)\n'
'- **Atos puramente vinculados** em que a motivação coincide integralmente com o suporte legal\n'
'- **Atos ad nutum** de cargos em comissão (mas atenção à teoria dos motivos determinantes)\n\n'
'Mesmo nessas hipóteses, a Lei 9.784/99 tende a exigir motivação genérica.\n\n'
'## 9. Consequência da ausência de motivação\n\n'
'A ausência ou insuficiência de motivação configura **vício de forma** (motivação é forma) e **vício de motivo** (se não há motivo demonstrado). Consequência:\n\n'
'- **Nulidade do ato** — em regra\n'
'- **Possibilidade de convalidação** apenas se o vício for de forma sanável (raro)\n'
'- **Direito à anulação por ação judicial ou administrativa**\n\n'
'## 10. Motivação e atos jurisdicionais\n\n'
'A CF art. 93, IX impõe motivação a todas as decisões judiciais sob pena de **nulidade**. A não-motivação ou motivação per relationem deficiente fundamenta recurso/embargos. A jurisprudência admite motivação concisa, desde que aborde os pontos essenciais (STF, AI 791.292 QO-RG).\n\n'
'## 11. Aplicação prática em concursos\n\n'
'**Casos típicos:**\n'
'- Indeferimento de pedido de servidor — exige motivação (art. 50, I, Lei 9.784/99)\n'
'- Aplicação de sanção disciplinar — exige motivação (art. 50, II)\n'
'- Dispensa de licitação — exige motivação (art. 50, IV)\n'
'- Indeferimento de recurso administrativo — exige motivação (art. 50, V)\n'
'- Anulação ou revogação de outro ato — exige motivação (art. 50, VIII)\n\n'
'**Pegadinhas frequentes:**\n'
'- "Atos vinculados dispensam motivação" — controvertido; majoritariamente exige ao menos referência ao dispositivo\n'
'- "Atos discricionários dispensam motivação" ❌ — exigem mais ainda\n'
'- "Motivação per relationem é nula" ❌ — é admitida pela jurisprudência\n'
'- "Motivo é elemento; motivação é princípio" ✅\n'
'- "Teoria dos motivos determinantes aplica-se aos atos discricionários" ✅\n\n'
'## 12. Conclusão\n\n'
'O princípio da motivação concretiza a transparência, o controle e o devido processo legal substantivo. Após a Lei 9.784/99, o dever de motivar deixou de ser "regra de bom administrador" e passou a ser **exigência jurídica positiva**. Para a banca, dominar a distinção motivo/motivação, a teoria dos motivos determinantes e o rol do art. 50 garante acertos certos.\n',

  'Motivação é a exposição expressa dos fundamentos de fato (motivo) e de direito que justificam o ato administrativo (Lei 9.784/99 art. 50). Motivo é elemento (sem ele = ato nulo); motivação é exposição escrita. Teoria dos Motivos Determinantes: uma vez exposto o motivo, o ato fica vinculado a ele — se falso/inexistente, é nulo (aplica-se até a atos discricionários e ad nutum). Motivação per relationem (referência a parecer) é admitida. Atos discricionários EXIGEM motivação para permitir controle. Ausência = vício de forma e/ou motivo = nulidade.'
);

