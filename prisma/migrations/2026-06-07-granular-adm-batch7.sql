E'# Princípio da Autotutela\n\n'
'## 1. Conceito\n\n'
'O princípio da autotutela confere à Administração Pública o poder-dever de **rever seus próprios atos** quando:\n\n'
'1. **Ilegais** → deve **anulá-los** (autotutela da legalidade)\n'
'2. **Inconvenientes ou inoportunos** → pode **revogá-los**, desde que respeitados direitos adquiridos (autotutela da conveniência)\n\n'
'A autotutela manifesta-se também na **vigilância sobre o patrimônio** e **bens públicos**, na **defesa contra invasão**, na **execução direta de obrigações**, configurando-se como uma das **prerrogativas mais relevantes** da Administração.\n\n'
'## 2. Fundamento normativo\n\n'
'### 2.1. Constituição Federal\n\n'
'Princípio implícito, derivado da legalidade (CF art. 37, caput).\n\n'
'### 2.2. Súmulas históricas do STF\n\n'
'**Súmula 346 STF (1963):** *"A Administração Pública pode declarar a nulidade dos seus próprios atos."*\n\n'
'**Súmula 473 STF (1969):** *"A administração pode anular seus próprios atos, quando eivados de vícios que os tornam ilegais, porque deles não se originam direitos; ou revogá-los, por motivo de conveniência ou oportunidade, respeitados os direitos adquiridos, e ressalvada, em todos os casos, a apreciação judicial."*\n\n'
'### 2.3. Lei 9.784/99 (Processo Administrativo Federal)\n\n'
'- **Art. 53:** *"A Administração deve anular seus próprios atos, quando eivados de vício de legalidade, e pode revogá-los por motivo de conveniência ou oportunidade, respeitados os direitos adquiridos."* (positiva o conteúdo da Súmula 473)\n'
'- **Art. 54:** prazo decadencial de **5 anos** para anulação de atos que produzam efeitos favoráveis a destinatários de boa-fé (salvo má-fé)\n'
'- **Art. 55:** convalidação de atos com vício sanável\n\n'
'### 2.4. CPC art. 884\n\n'
'A Administração tem prerrogativas processuais decorrentes da autotutela (presunção de legitimidade, executoriedade).\n\n'
'## 3. Anulação\n\n'
'### 3.1. Conceito\n\n'
'Anulação é o **desfazimento do ato administrativo por vício de legalidade**. Recai sobre atos:\n\n'
'- **Em desacordo com a lei** (vícios de qualquer dos 5 elementos: competência, finalidade, forma, motivo, objeto)\n'
'- **Eivados de nulidade ou anulabilidade**\n\n'
'### 3.2. Características\n\n'
'- **Dever (não faculdade)** — Administração obrigada a anular ilegalidades\n'
'- **Efeito ex tunc** (retroativo) — desfaz tudo desde a origem\n'
'- **Pode ser feita pela Administração** ou determinada pelo Judiciário\n'
'- **Sujeita a prazo de 5 anos** para atos favoráveis a destinatário de boa-fé (Lei 9.784/99 art. 54)\n'
'- **Exige contraditório** quando afeta interesses (CF 5º, LV; Lei 9.784/99)\n\n'
'### 3.3. Excepcionalidade: atos benéficos\n\n'
'Mesmo ilegal, o ato que beneficia o particular de boa-fé pode ser **mantido por segurança jurídica** quando se passaram mais de 5 anos. Após esse prazo, há **decadência do direito de anular** (Lei 9.784/99 art. 54).\n\n'
'A Súmula 473, portanto, **deve ser lida em conjunto com o art. 54** da Lei 9.784/99 — temperada por boa-fé e segurança jurídica.\n\n'
'## 4. Revogação\n\n'
'### 4.1. Conceito\n\n'
'Revogação é o **desfazimento do ato administrativo por motivo de conveniência ou oportunidade**. Recai sobre atos:\n\n'
'- **Válidos** (legais), mas\n'
'- **Inoportunos ou inconvenientes** ao interesse público\n\n'
'### 4.2. Características\n\n'
'- **Faculdade discricionária** da Administração\n'
'- **Efeito ex nunc** (não retroativo) — preserva os atos já praticados\n'
'- **Só pode ser feita pela Administração** (Judiciário não revoga, só anula por ilegalidade)\n'
'- **Respeita direitos adquiridos** (não atinge direitos consolidados)\n\n'
'### 4.3. Atos irrevogáveis\n\n'
'Não podem ser revogados:\n\n'
'1. **Atos vinculados** — pois não há juízo de conveniência\n'
'2. **Atos que já exauriram seus efeitos** — não há mais o que revogar\n'
'3. **Atos que geraram direitos adquiridos** — proteção constitucional (CF 5º, XXXVI)\n'
'4. **Atos enunciativos** (certidões, atestados) — meramente declaram\n'
'5. **Atos processuais administrativos** (decisões finais que viraram preclusão)\n'
'6. **Atos integrativos** (aprovações, homologações que se incorporaram a ato complexo concluído)\n\n'
